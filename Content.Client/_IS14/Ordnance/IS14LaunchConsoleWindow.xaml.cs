using Content.Client.UserInterface.Controls;
using Content.Shared._IS14.Ordnance;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._IS14.Ordnance;

/// <summary>Launch control: set the delay, fire, or call it off while the clock runs.</summary>
[GenerateTypedNameReferences]
public sealed partial class IS14LaunchConsoleWindow : FancyWindow
{
    public event Action? OnLaunch;
    public event Action? OnAbort;
    public event Action<int>? OnCountdownChanged;

    public IS14LaunchConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        CountdownSpin.IsValid = value => value is >= 3 and <= 60;
        CountdownSpin.ValueChanged += args => OnCountdownChanged?.Invoke(args.Value);

        LaunchButton.OnPressed += _ => OnLaunch?.Invoke();
        AbortButton.OnPressed += _ => OnAbort?.Invoke();
    }

    public void UpdateState(IS14LaunchConsoleUiState state)
    {
        var counting = state.SecondsLeft != null;

        StatusLabel.Text = counting
            ? Loc.GetString("is14-launch-console-counting", ("seconds", state.SecondsLeft!.Value))
            : Loc.GetString("is14-launch-console-ready");

        StatusLabel.FontColorOverride = counting ? Color.FromHex("#e8fa25") : Color.FromHex("#7ecd48");

        // What the chamber consists of is whatever somebody wired to the three outputs.
        var wired = state.LaunchLinks > 0;

        HardwareLabel.Text = wired
            ? Loc.GetString("is14-launch-console-links",
                ("pre", state.PreLinks),
                ("launch", state.LaunchLinks),
                ("post", state.PostLinks),
                ("lead", state.LeadSeconds))
            : Loc.GetString("is14-launch-console-not-linked");

        HardwareLabel.FontColorOverride = wired ? Color.FromHex("#9a9a9a") : Color.FromHex("#c07a7a");

        // OverrideValue, not Value: the setter raises ValueChanged, which would send the value
        // straight back to the server and fight whatever the player is typing. And only when it
        // actually differs, so a state push mid-edit does not yank the field from under them.
        if (CountdownSpin.Value != state.Countdown)
            CountdownSpin.OverrideValue(state.Countdown);

        CountdownSpin.Visible = !counting;

        LaunchButton.Disabled = counting || !wired;
        AbortButton.Visible = counting;
    }
}

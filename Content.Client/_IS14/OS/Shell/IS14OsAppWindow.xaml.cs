using System.Numerics;
using Content.Client._IS14.Controls;
using Robust.Client.GameObjects;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._IS14.OS.Shell;

/// <summary>
///     One application window inside the desktop. Built on the engine's BaseWindow, which
///     already drags relative to its parent and clamps to the parent's size — so a window can
///     never leave the device screen and no custom window manager is needed (Docs §5.1).
///     In fullscreen mode (handhelds) the same window simply fills the desktop and stops
///     dragging: one implementation, two shell modes.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class IS14OsAppWindow : BaseWindow
{
    private const int DragMargin = 6;
    private const int TitleBarHeight = 22;

    // XamlIL requires a public parameterless constructor on every XAML root type, so identity
    // is handed over by Initialize rather than through the constructor.
    public string AppId { get; private set; } = string.Empty;
    public IS14OsAppUi Ui { get; private set; } = default!;

    private bool _fullscreen;

    public event Action<string>? OnCloseRequested;
    public event Action<string>? OnMinimizeRequested;
    public event Action<string>? OnFocusRequested;

    public string? Title
    {
        get => TitleLabel.Text;
        set => TitleLabel.Text = value;
    }

    public Texture? Icon
    {
        get => TitleIcon.Texture;
        set
        {
            TitleIcon.Texture = value;
            TitleIcon.Visible = value != null;
        }
    }

    public IS14OsAppWindow()
    {
        RobustXamlLoader.Load(this);

        CloseAppButton.OnPressed += _ => OnCloseRequested?.Invoke(AppId);
        MinimizeButton.OnPressed += _ => OnMinimizeRequested?.Invoke(AppId);
        FooterCloseButton.OnPressed += _ => OnCloseRequested?.Invoke(AppId);

        var sprites = IoCManager.Resolve<IEntitySystemManager>().GetEntitySystem<SpriteSystem>();
        CloseAppButton.TextureNormal = IS14OsStyle.Resolve(sprites, IS14OsStyle.Close);
        MinimizeButton.TextureNormal = IS14OsStyle.Resolve(sprites, IS14OsStyle.Minimize);
        FooterCloseButton.Icon = IS14OsStyle.Resolve(sprites, IS14OsStyle.Close);
        FooterCloseButton.Caption = Loc.GetString("is14-os-window-close");
    }

    public void Initialize(string appId, IS14OsAppUi ui)
    {
        AppId = appId;
        Ui = ui;

        ContentHost.AddChild(ui.Root);
    }

    /// <summary>
    ///     Fullscreen pins the window to the whole desktop and turns off dragging and resizing.
    ///     The minimise button stays: on a handheld it is how you get back to the task switcher.
    /// </summary>
    public void SetFullscreen(bool fullscreen)
    {
        if (_fullscreen == fullscreen)
            return;

        _fullscreen = fullscreen;
        Resizable = !fullscreen;

        if (fullscreen)
        {
            // Clear any explicit size (NaN is the "unset" value) and dock to the whole desktop.
            SetSize = new Vector2(float.NaN, float.NaN);
            LayoutContainer.SetAnchorAndMarginPreset(this, LayoutContainer.LayoutPreset.Wide);
        }
    }

    public void ApplyTheme(IS14ThemePalette palette)
    {
        Chrome.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = palette.Panel,
            BorderColor = palette.Border,
            BorderThickness = new Thickness(_fullscreen ? 0 : 1),
        };

        TitleBarPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = palette.PanelRaised,
            BorderColor = palette.Border,
            BorderThickness = new Thickness(0, 0, 0, 1),
        };

        ContentPanel.PanelOverride = new StyleBoxFlat { BackgroundColor = palette.Panel };

        FooterPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = palette.PanelRaised,
            BorderColor = palette.Border,
            BorderThickness = new Thickness(0, 1, 0, 0),
        };

        FooterCloseButton.Palette = palette;

        TitleLabel.FontColorOverride = palette.Accent;
        TitleIcon.ModulateSelfOverride = palette.Accent;
        MinimizeButton.ModulateSelfOverride = palette.Muted;
        CloseAppButton.ModulateSelfOverride = palette.Bad;
    }

    protected override void KeyBindDown(GUIBoundKeyEventArgs args)
    {
        base.KeyBindDown(args);
        OnFocusRequested?.Invoke(AppId);
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        if (_fullscreen)
            return DragMode.None;

        var mode = DragMode.None;

        if (Resizable)
        {
            if (relativeMousePos.Y < DragMargin)
                mode = DragMode.Top;
            else if (relativeMousePos.Y > Size.Y - DragMargin)
                mode = DragMode.Bottom;

            if (relativeMousePos.X < DragMargin)
                mode |= DragMode.Left;
            else if (relativeMousePos.X > Size.X - DragMargin)
                mode |= DragMode.Right;
        }

        if (mode == DragMode.None && relativeMousePos.Y < TitleBarHeight)
            mode = DragMode.Move;

        return mode;
    }
}

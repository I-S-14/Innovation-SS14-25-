/// <summary>
///     To-do list. Deliberately the plainest app on the platform: type a line, tick it off,
///     sweep the ticked ones away.
/// </summary>
public sealed class TasksAppUi : IS14OsAppUi
{
    private TasksAppFragment? _fragment;

    private TasksAppFragment Fragment => _fragment ??= new TasksAppFragment();

    public override string AppId => "AppTasks";

    public override Control Root => Fragment;

    public override void Setup(IS14OsBui bui)
    {
        base.Setup(bui);

        Fragment.OnAdd += text => SendAppEvent(AppId, new OsTaskAddEvent(text));
        Fragment.OnToggle += id => SendAppEvent(AppId, new OsTaskToggleEvent(id));
        Fragment.OnRemove += id => SendAppEvent(AppId, new OsTaskRemoveEvent(id));
    }

    public override void UpdateState(IS14OsAppState state)
    {
        if (state is OsTasksState tasks)
            Fragment.UpdateState(tasks);
    }

    public override void ApplyTheme(IS14ThemePalette palette)
    {
        Fragment.ApplyTheme(palette);
    }
}

[GenerateTypedNameReferences]
public sealed partial class TasksAppFragment : BoxContainer
{
    [Dependency] private readonly IEntitySystemManager _sysMan = default!;

    private readonly SpriteSystem _sprites;
    private readonly Texture? _checkIcon;
    private readonly Texture? _boxIcon;
    private readonly Texture? _deleteIcon;

    private IS14ThemePalette _palette = IS14ThemePalette.Default;
    private OsTasksState? _state;

    public event Action<string>? OnAdd;
    public event Action<int>? OnToggle;

    /// <summary>Null sweeps everything already done; an id removes that one entry.</summary>
    public event Action<int?>? OnRemove;

    public TasksAppFragment()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        VerticalExpand = true;

        _sprites = _sysMan.GetEntitySystem<SpriteSystem>();
        _checkIcon = IS14OsStyle.Resolve(_sprites, IS14OsStyle.Check);
        _boxIcon = IS14OsStyle.Resolve(_sprites, IS14OsStyle.Box);
        _deleteIcon = IS14OsStyle.Resolve(_sprites, IS14OsStyle.Delete);

        AddEdit.PlaceHolder = Loc.GetString("is14-os-tasks-placeholder");
        AddEdit.OnTextEntered += _ => Submit();

        AddButton.Icon = IS14OsStyle.Resolve(_sprites, IS14OsStyle.Plus);
        AddButton.ToolTip = Loc.GetString("is14-os-tasks-add");
        AddButton.OnPressed += _ => Submit();

        ClearButton.Icon = _deleteIcon;
        ClearButton.Caption = Loc.GetString("is14-os-tasks-clear");
        ClearButton.ToolTip = Loc.GetString("is14-os-tasks-clear-tooltip");
        ClearButton.OnPressed += _ => OnRemove?.Invoke(null);
    }

    private void Submit()
    {
        var text = AddEdit.Text.Trim();
        if (text.Length == 0)
            return;

        AddEdit.Text = string.Empty;
        OnAdd?.Invoke(text);
    }

    public void UpdateState(OsTasksState state)
    {
        _state = state;
        Rebuild();
    }

    private void Rebuild()
    {
        TaskList.RemoveAllChildren();

        if (_state == null)
            return;

        var done = _state.Tasks.Count(t => t.Done);

        CountLabel.Text = Loc.GetString("is14-os-tasks-count",
            ("done", done),
            ("total", _state.Tasks.Count));
        CountLabel.FontColorOverride = _state.Full ? _palette.Warn : _palette.Muted;

        ClearButton.Disabled = done == 0;

        if (_state.Tasks.Count == 0)
        {
            TaskList.AddChild(new Label
            {
                Text = Loc.GetString("is14-os-tasks-empty"),
                FontColorOverride = _palette.Muted,
            });

            return;
        }

        foreach (var task in _state.Tasks)
        {
            var id = task.Id;

            var row = new StatRow
            {
                Palette = _palette,
                Framed = true,
                Icon = task.Done ? _checkIcon : _boxIcon,
                Caption = task.Text,
                Margin = new Thickness(0, 0, 0, 2),
            };

            // A finished line stays legible but stops competing for attention with the rest.
            if (task.Done)
                row.ModulateSelfOverride = _palette.Muted;

            var buttons = new BoxContainer { Orientation = LayoutOrientation.Horizontal };

            var toggle = new IconTile
            {
                Palette = _palette,
                Compact = true,
                Icon = task.Done ? _boxIcon : _checkIcon,
                IconSize = 12,
                ToolTip = Loc.GetString(task.Done ? "is14-os-tasks-undo" : "is14-os-tasks-done"),
                Margin = new Thickness(0, 0, 3, 0),
            };
            toggle.OnPressed += _ => OnToggle?.Invoke(id);

            var remove = new IconTile
            {
                Palette = _palette,
                Compact = true,
                Icon = _deleteIcon,
                IconSize = 12,
                ToolTip = Loc.GetString("is14-os-tasks-remove"),
            };

            remove.OnPressed += _ =>
            {
                remove.Disabled = true;
                OnRemove?.Invoke(id);
            };

            buttons.AddChild(toggle);
            buttons.AddChild(remove);
            row.SetTrailing(buttons);

            TaskList.AddChild(row);
        }
    }

    public void ApplyTheme(IS14ThemePalette palette)
    {
        _palette = palette;

        AddButton.Palette = palette;
        ClearButton.Palette = palette;
        Rebuild();
    }
}

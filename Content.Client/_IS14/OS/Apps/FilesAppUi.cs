/// <summary>
///     Files: what is installed and what it costs in memory. Memory is the platform's main
///     constraint, so this app is where the player actually feels it (Docs §7.2).
/// </summary>
public sealed class FilesAppUi : IS14OsAppUi
{
    private FilesAppFragment? _fragment;

    private FilesAppFragment Fragment => _fragment ??= new FilesAppFragment();

    public override string AppId => "AppFiles";

    public override Control Root => Fragment;

    public override void Setup(IS14OsBui bui)
    {
        base.Setup(bui);

        Fragment.OnUninstall += app => Bui.SendUninstall(app);
    }

    public override void UpdateShell(OsShellState shell)
    {
        Fragment.UpdateShell(shell);
    }

    public override void ApplyTheme(IS14ThemePalette palette)
    {
        Fragment.ApplyTheme(palette);
    }
}

[GenerateTypedNameReferences]
public sealed partial class FilesAppFragment : BoxContainer
{
    /// <summary>Above this share of memory the readout warns; above the second it shouts.</summary>
    private const float WarnAt = 0.7f;
    private const float FullAt = 0.9f;

    [Dependency] private readonly IPrototypeManager _proto = default!;
    [Dependency] private readonly IEntitySystemManager _sysMan = default!;

    private readonly SpriteSystem _sprites;
    private readonly Texture? _deleteIcon;

    private IS14ThemePalette _palette = IS14ThemePalette.Default;
    private OsShellState? _shell;

    public event Action<string>? OnUninstall;

    public FilesAppFragment()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        VerticalExpand = true;

        _sprites = _sysMan.GetEntitySystem<SpriteSystem>();
        _deleteIcon = IS14OsStyle.Resolve(_sprites, IS14OsStyle.Delete);

        MemoryIcon.Texture = IS14OsStyle.Resolve(_sprites, IS14OsStyle.Memory);
        MemoryCaption.Text = Loc.GetString("is14-os-files-memory-caption");

        // Used memory is the bad direction, so the usual "low is bad" colours are flipped.
        MemoryBar.LowThreshold = WarnAt;
        MemoryBar.WarnThreshold = FullAt;
    }

    public void UpdateShell(OsShellState shell)
    {
        _shell = shell;

        var used = shell.MemorySystem + shell.MemoryUsed;
        var total = Math.Max(1, shell.MemoryTotal);
        var free = Math.Max(0, shell.MemoryTotal - used);

        MemoryValue.Text = Loc.GetString("is14-os-files-memory", ("used", used), ("total", shell.MemoryTotal));
        MemoryBreakdown.Text = Loc.GetString("is14-os-files-memory-breakdown",
            ("system", shell.MemorySystem),
            ("apps", shell.MemoryUsed));
        MemoryFree.Text = Loc.GetString("is14-os-files-memory-free", ("free", free));

        var fill = Math.Clamp((float) used / total, 0f, 1f);
        MemoryBar.Fraction = fill;

        var color = fill > FullAt ? _palette.Bad : fill > WarnAt ? _palette.Warn : _palette.Good;
        MemoryValue.FontColorOverride = color;
        MemoryFree.FontColorOverride = color;

        RebuildList(shell);
    }

    private void RebuildList(OsShellState shell)
    {
        AppList.RemoveAllChildren();

        AppList.AddChild(new StatRow
        {
            Palette = _palette,
            Caption = Loc.GetString("is14-os-files-system"),
            Value = Loc.GetString("is14-os-files-size", ("size", shell.MemorySystem)),
            Margin = new Thickness(0, 0, 0, 3),
        });

        foreach (var appId in shell.Installed)
        {
            if (appId.Id is not { } id || !_proto.TryIndex<IS14OsAppPrototype>(id, out var app))
                continue;

            if (app.Undeletable)
                continue;

            var row = new StatRow
            {
                Palette = _palette,
                Framed = true,
                Icon = IS14OsStyle.Resolve(_sprites, app.Icon ?? IS14OsStyle.Fallback),
                Caption = Loc.GetString(app.Name),
                Value = Loc.GetString("is14-os-files-size", ("size", app.Size)),
                Margin = new Thickness(0, 0, 0, 2),
                ToolTip = app.Description == null ? null : Loc.GetString(app.Description),
            };

            var button = new IconTile
            {
                Palette = _palette,
                Compact = true,
                Icon = _deleteIcon,
                IconSize = 12,
                ToolTip = Loc.GetString("is14-os-files-uninstall"),
            };

            button.OnPressed += _ =>
            {
                // The list only refreshes on the next state push, so lock the button now —
                // otherwise a second click asks to remove something already gone.
                button.Disabled = true;
                OnUninstall?.Invoke(id);
            };

            row.SetTrailing(button);
            AppList.AddChild(row);
        }
    }

    public void ApplyTheme(IS14ThemePalette palette)
    {
        _palette = palette;

        MemoryPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = palette.PanelRaised,
            BorderColor = palette.Border,
            BorderThickness = new Thickness(1),
        };

        MemoryIcon.ModulateSelfOverride = palette.Accent;
        MemoryCaption.FontColorOverride = palette.Text;
        MemoryBreakdown.FontColorOverride = palette.Muted;

        MemoryBar.BackgroundColor = palette.Backdrop;
        MemoryBar.TickColor = palette.Border;
        MemoryBar.LowColor = palette.Good;
        MemoryBar.WarnColor = palette.Warn;
        MemoryBar.FullColor = palette.Bad;

        if (_shell != null)
            UpdateShell(_shell);
    }
}

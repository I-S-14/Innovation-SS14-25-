/// <summary>
///     Camera. Photographs what the holder can see, on its own eye: the frame can be widened
///     and aimed without touching the player's own view.
/// </summary>
public sealed class CameraAppUi : IS14OsAppUi
{
    private CameraAppFragment? _fragment;

    private CameraAppFragment Fragment => _fragment ??= new CameraAppFragment();

    public override string AppId => "AppCamera";

    public override Control Root => Fragment;

    public override void Setup(IS14OsBui bui)
    {
        base.Setup(bui);

        Fragment.OnCapture += bytes => SendAppEvent(AppId, new OsCameraCaptureEvent(bytes));
    }

    public override void UpdateState(IS14OsAppState state)
    {
        if (state is OsCameraState camera)
            Fragment.UpdateState(camera);
    }

    public override void ApplyTheme(IS14ThemePalette palette)
    {
        Fragment.ApplyTheme(palette);
    }
}

[GenerateTypedNameReferences]
public sealed partial class CameraAppFragment : BoxContainer
{
    private const string SliderRoot = "/Textures/Interface/Nano/";

    /// <summary>
    ///     Frame size, in tiles. Two is a portrait, five is a room. The player never sees this
    ///     number: the widest frame is x1 and everything tighter is magnification, which is how
    ///     a camera has always been labelled.
    /// </summary>
    private const float MinTiles = 2f;
    private const float MaxTiles = 5f;
    private const float DefaultTiles = 4f;

    /// <summary>How far from the holder the frame may be aimed, in tiles.</summary>
    private const float MaxPan = 3f;

    [Dependency] private readonly IEyeManager _eye = default!;
    [Dependency] private readonly IEntitySystemManager _sysMan = default!;
    [Dependency] private readonly IResourceCache _cache = default!;

    /// <summary>
    ///     The camera's own eye. It follows the holder, but carries its own zoom and offset, so
    ///     changing the frame never touches what the player themselves sees. The offset does not
    ///     move the centre of the FOV, so aiming the frame past a wall shows darkness rather
    ///     than what is behind it.
    /// </summary>
    private readonly FixedEye _camera = new();

    private Vector2 _pan;
    private float _tiles;
    private bool _capturing;

    public event Action<byte[]>? OnCapture;

    public CameraAppFragment()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Orientation = LayoutOrientation.Horizontal;
        HorizontalExpand = true;
        VerticalExpand = true;

        _camera.Zoom = Vector2.One;
        IS14CleanView.Register(_camera);

        View.Eye = _camera;
        SetTiles(DefaultTiles);

        var sprites = _sysMan.GetEntitySystem<SpriteSystem>();

        // The slider runs in magnification, not tiles: it grows to the right the way every
        // zoom control does, and the tightest frame is the far end.
        ZoomSlider.MinValue = ZoomOf(MaxTiles);
        ZoomSlider.MaxValue = ZoomOf(MinTiles);
        ZoomSlider.SetValueWithoutEvent(ZoomOf(DefaultTiles));
        ZoomSlider.OnValueChanged += slider => SetZoom(slider.Value);

        ViewDrag.ToolTip = Loc.GetString("is14-os-camera-aim-hint");
        ViewDrag.OnDragged += Pan;

        CenterButton.Icon = IS14OsStyle.Resolve(sprites, IS14OsStyle.Center);
        CenterButton.Caption = Loc.GetString("is14-os-camera-center");
        CenterButton.ToolTip = Loc.GetString("is14-os-camera-center");
        CenterButton.OnPressed += _ => _pan = Vector2.Zero;

        ShutterButton.ToolTip = Loc.GetString("is14-os-camera-shoot");
        ShutterButton.OnPressed += _ => Capture();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // The player's eye moves with them, and is replaced outright when they are possessed or
        // shoved in a locker; ours only borrows its position.
        var current = _eye.CurrentEye;

        _camera.Position = current.Position;
        _camera.Rotation = current.Rotation;
        _camera.Offset = _pan;
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (disposing)
            IS14CleanView.Unregister(_camera);
    }

    #region Framing

    /// <summary>Magnification for a frame this wide: the widest frame is x1 by definition.</summary>
    private static float ZoomOf(float tiles)
    {
        return MaxTiles / tiles;
    }

    private void SetZoom(float zoom)
    {
        // A tenth of a step is as fine as the readout goes, so snap to it rather than letting
        // the label round two different drags to the same number.
        zoom = MathF.Round(Math.Clamp(zoom, ZoomOf(MaxTiles), ZoomOf(MinTiles)), 1);
        SetTiles(MaxTiles / zoom);
    }

    private void SetTiles(float tiles)
    {
        _tiles = Math.Clamp(tiles, MinTiles, MaxTiles);

        // A tile is 32 pixels and the eye is not zoomed, so the frame is that many tiles across
        // and the photo is exactly that many tiles of pixels. A wider shot really does cost more
        // memory, which keeps the constraint honest (Docs §7.2).
        var side = (int) MathF.Round(_tiles * EyeManager.PixelsPerMeter);
        View.ViewportSize = new Vector2i(side, side);

        var zoom = MathF.Round(ZoomOf(_tiles), 1).ToString("0.0", CultureInfo.InvariantCulture);
        ZoomLabel.Text = Loc.GetString("is14-os-camera-zoom", ("zoom", zoom));
    }

    /// <summary>Drags the picture rather than the camera: the world follows the cursor.</summary>
    private void Pan(Vector2 delta)
    {
        // Ask the viewport where the drag landed instead of deriving it. It already knows the
        // frame's scale, the letterboxing inside the panel and — the part that bit us — which
        // way the eye is rotated, so the picture follows the cursor on a spun grid too.
        // Its screen space is real pixels, while a UI delta is virtual ones.
        var origin = (Vector2) View.GlobalPixelPosition + (Vector2) View.PixelSize / 2f;

        var from = View.ScreenToMap(origin);
        var to = View.ScreenToMap(origin + delta * View.UIScale);

        if (from.MapId != to.MapId)
            return;

        _pan += from.Position - to.Position;

        if (_pan.Length() > MaxPan)
            _pan = Vector2.Normalize(_pan) * MaxPan;
    }

    #endregion

    private void Capture()
    {
        if (_capturing)
            return;

        _capturing = true;
        ShutterButton.Disabled = true;

        View.Screenshot(image =>
        {
            using var data = new MemoryStream();
            image.SaveAsPng(data);
            image.Dispose();

            _capturing = false;
            ShutterButton.Disabled = false;
            OnCapture?.Invoke(data.ToArray());
        });
    }

    public void UpdateState(OsCameraState state)
    {
        CountLabel.Text = Loc.GetString("is14-os-camera-count", ("count", state.Photos));
        StatusLabel.Text = state.Status == null ? string.Empty : Loc.GetString(state.Status);
    }

    public void ApplyTheme(IS14ThemePalette palette)
    {
        ViewPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = palette.Backdrop,
            BorderColor = palette.Border,
            BorderThickness = new Thickness(1),
        };

        StatusLabel.FontColorOverride = palette.Good;
        CountLabel.FontColorOverride = palette.Muted;
        ZoomLabel.FontColorOverride = palette.Accent;

        CenterButton.Palette = palette;
        ShutterButton.Palette = palette;

        // The stock slider is Nanotrasen green whatever the theme says, so it gets repainted
        // from the same textures the default sheet uses.
        ZoomSlider.BackgroundStyleBoxOverride = Bar("slider_fill.svg.96dpi.png", palette.Backdrop);
        ZoomSlider.FillStyleBoxOverride = Bar("slider_fill.svg.96dpi.png", palette.Accent);
        ZoomSlider.ForegroundStyleBoxOverride = Bar("slider_outline.svg.96dpi.png", palette.Border);
        ZoomSlider.GrabberStyleBoxOverride = Bar("slider_grabber.svg.96dpi.png", palette.BorderBright);
    }

    private StyleBoxTexture Bar(string texture, Color color)
    {
        var box = new StyleBoxTexture
        {
            Texture = _cache.GetTexture(SliderRoot + texture),
            Modulate = color,
        };

        box.SetPatchMargin(StyleBox.Margin.All, 12);
        return box;
    }
}

        SaveFileButton.Icon = IS14OsStyle.Resolve(sprites, IS14OsStyle.SaveFile);
        SaveFileButton.ToolTip = Loc.GetString("is14-os-notes-export-tooltip");
        SaveFileButton.OnPressed += _ => OnExport?.Invoke(ExportName());


/// <summary>
///     The document editor. Formatting is the engine's own markup — the same tags rich text
///     uses everywhere else in the game — so the toolbar is really a tag inserter and the
///     preview is a <see cref="RichTextLabel"/>. That keeps what the player writes portable:
///     a document exported to a file reads the same in Files or in a messenger attachment.
/// </summary>
public sealed class NotesAppUi : IS14OsAppUi
{
    private NotesAppFragment? _fragment;

    private NotesAppFragment Fragment => _fragment ??= new NotesAppFragment();

    public override string AppId => "AppNotes";

    public override Control Root => Fragment;

    public override void Setup(IS14OsBui bui)
    {
        base.Setup(bui);

        Fragment.OnSave += (text, title) => SendAppEvent(AppId, new OsNotesSaveEvent(text, title));
        Fragment.OnExport += name => SendAppEvent(AppId, new OsNotesExportEvent(name));
    }

    /// <summary>
    ///     Last chance to keep what the writer typed: the moment the window is gone the server
    ///     stops accepting the app's events, so an unsaved document would go with it.
    /// </summary>
    public override void Closing()
    {
        Fragment.Flush();
    }

    public override void UpdateState(IS14OsAppState state)
    {
        if (state is OsNotesState notes)
            Fragment.UpdateState(notes);
    }

    public override void ApplyTheme(IS14ThemePalette palette)
    {
        Fragment.ApplyTheme(palette);
    }
}


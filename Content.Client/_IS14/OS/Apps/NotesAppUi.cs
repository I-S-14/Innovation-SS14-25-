    #region Editing

    /// <summary>
    ///     Wraps the selection in a tag pair, or opens an empty one at the caret. Both are what
    ///     a formatting button does in a word processor: with text selected it formats it, with
    ///     nothing selected it turns the style on for whatever gets typed next.
    ///
    ///     Pressing it on text that already carries the tag takes it off again. A button that
    ///     only ever adds would leave <c>[bold][bold]x[/bold][/bold]</c> behind, and the writer
    ///     cannot see the difference until it is time to pick the brackets out by hand.
    /// </summary>
    private void Wrap(string open, string close)
    {
        var text = Rope.Collapse(NoteEdit.TextRope);
        var lower = NoteEdit.SelectionLower.Index;
        var upper = NoteEdit.SelectionUpper.Index;
        var selected = text[lower..upper];

        if (TryUnwrap(text, lower, upper, selected, open, close))
            return;

        NoteEdit.InsertAtCursor(open + selected + close);

        // Nothing was selected: park the caret between the tags so typing lands inside them.
        if (selected.Length == 0)
            NoteEdit.CursorPosition = new TextEdit.CursorPos(lower + open.Length, TextEdit.LineBreakBias.Top);

        // InsertAtCursor raises OnTextChanged for us, so the status bar is already up to date.
        NoteEdit.GrabKeyboardFocus();
    }

    /// <summary>
    ///     Takes the tag pair off again, whether the writer selected the tags along with the
    ///     text or only the text between them.
    /// </summary>
    private bool TryUnwrap(string text, int lower, int upper, string selected, string open, string close)
    {
        if (selected.Length >= open.Length + close.Length
            && selected.StartsWith(open, StringComparison.Ordinal)
            && selected.EndsWith(close, StringComparison.Ordinal))
        {
            var inner = selected[open.Length..^close.Length];
            SetText(text[..lower] + inner + text[upper..], lower + inner.Length);
            return true;
        }

        if (lower >= open.Length
            && upper + close.Length <= text.Length
            && string.CompareOrdinal(text, lower - open.Length, open, 0, open.Length) == 0
            && string.CompareOrdinal(text, upper, close, 0, close.Length) == 0)
        {
            var start = lower - open.Length;
            SetText(text[..start] + selected + text[(upper + close.Length)..], start + selected.Length);
            return true;
        }

        return false;
    }

    /// <summary>A bullet belongs at the start of its line, not wherever the caret happens to sit.</summary>
    private void InsertBullet()
    {
        const string bullet = "[bullet]";

        var text = Rope.Collapse(NoteEdit.TextRope);
        var caret = Math.Clamp(NoteEdit.CursorPosition.Index, 0, text.Length);

        var start = 0;
        for (var i = caret - 1; i >= 0; i--)
        {
            if (text[i] != '\n')
                continue;

            start = i + 1;
            break;
        }

        SetText(text.Insert(start, bullet), caret + bullet.Length);
    }

    /// <summary>
    ///     Strips the tags out of the selection, or out of the whole document when there is no
    ///     selection — Word clears formatting the same way.
    /// </summary>
    private void ClearFormatting()
    {
        var text = Rope.Collapse(NoteEdit.TextRope);
        var lower = NoteEdit.SelectionLower.Index;
        var upper = NoteEdit.SelectionUpper.Index;

        if (lower == upper)
        {
            lower = 0;
            upper = text.Length;
        }

        var stripped = Plain(text[lower..upper]);
        SetText(text[..lower] + stripped + text[upper..], lower + stripped.Length);
    }

    private void SetText(string text, int caret)
    {
        NoteEdit.TextRope = new Rope.Leaf(text);
        NoteEdit.CursorPosition = new TextEdit.CursorPos(Math.Clamp(caret, 0, text.Length),
            TextEdit.LineBreakBias.Top);

        NoteEdit.GrabKeyboardFocus();
        MarkEdited();
    }

    /// <summary>Writes the document back to the device if anything changed since last time.</summary>
    public void Flush()
    {
        if (_dirty)
            Save();
    }

    /// <summary>
    ///     The document saves itself once the writer pauses. A note that survives only if you
    ///     remember to press a button is a note that gets lost, and on a device someone can
    ///     make you drop there is no reliable moment to press it.
    /// </summary>
    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!_dirty)
            return;

        _idle += args.DeltaSeconds;

        if (_idle >= AutoSaveDelay)
            Save();
    }

    private void Save()
    {
        _dirty = false;
        _idle = 0f;

        _saved = Rope.Collapse(NoteEdit.TextRope);
        _savedTitle = TitleEdit.Text.Trim();

        SavedLabel.Text = Loc.GetString("is14-os-notes-saved");
        SavedLabel.FontColorOverride = _palette.Good;

        OnSave?.Invoke(_saved, _savedTitle);
    }

    /// <summary>The document's name, falling back to its first words the way a new file does.</summary>
    private string ExportName()
    {
        var title = TitleEdit.Text.Trim();
        if (title.Length > 0)
            return title;

        var plain = Plain(Rope.Collapse(NoteEdit.TextRope));
        return plain.Split('\n')[0].Trim();
    }

    #endregion

    #region State

    private void MarkEdited()
    {
        if (_loading)
            return;

        _dirty = Rope.Collapse(NoteEdit.TextRope) != _saved || TitleEdit.Text.Trim() != _savedTitle;
        _idle = 0f;

        if (_dirty)
        {
            SavedLabel.Text = Loc.GetString("is14-os-notes-unsaved");
            SavedLabel.FontColorOverride = _palette.Warn;
        }

        Refresh();
    }

    /// <summary>Status bar and, when it is showing, the rendered page.</summary>
    private void Refresh()
    {
        var text = Rope.Collapse(NoteEdit.TextRope);
        var plain = Plain(text);

        CountLabel.Text = Loc.GetString("is14-os-notes-count",
            ("words", CountWords(plain)),
            ("chars", text.Length),
            ("max", MaxLength));

        // The server truncates past the cap, so say so before it happens rather than after.
        CountLabel.FontColorOverride = text.Length > MaxLength ? _palette.Bad : _palette.Muted;

        if (PreviewPanel.Visible)
            UpdatePreview();
    }

    private void UpdatePreview()
    {
        var text = Rope.Collapse(NoteEdit.TextRope);

        FormattedMessage message;
        try
        {
            message = FormattedMessage.FromMarkupPermissive(text);
        }
        catch (Exception)
        {
            // Half-typed markup is normal in an editor: show it as plain text rather than
            // letting a parse error take the app down.
            message = FormattedMessage.FromUnformatted(text);
        }

        PreviewText.SetMessage(message, IS14DocumentText.Tags, _palette.Text);
    }

    public void UpdateState(OsNotesState state)
    {
        if (state.Status != null)
        {
            SavedLabel.Text = Loc.GetString(state.Status);
            SavedLabel.FontColorOverride = _palette.Good;
        }

        // Don't stomp on what the player is typing: only take the server's copy when it is
        // genuinely different from what we last sent.
        if (state.Text == _saved && state.Title == _savedTitle)
            return;

        _loading = true;

        _saved = state.Text;
        _savedTitle = state.Title;
        _dirty = false;
        _idle = 0f;

        NoteEdit.TextRope = new Rope.Leaf(state.Text);
        TitleEdit.Text = state.Title;

        if (state.Status == null)
            SavedLabel.Text = string.Empty;

        _loading = false;

        Refresh();
    }

    #endregion

    #region Markup

    /// <summary>
    ///     The text without its tags. Used for the word count and for clearing formatting, so
    ///     it has to survive half-written markup: a bracket with no closing one is text.
    /// </summary>
    private static string Plain(string markup)
    {
        var builder = new StringBuilder(markup.Length);

        var i = 0;
        while (i < markup.Length)
        {
            var c = markup[i];

            if (c == '\\' && i + 1 < markup.Length)
            {
                builder.Append(markup[i + 1]);
                i += 2;
                continue;
            }

            if (c == '[')
            {
                var end = markup.IndexOf(']', i + 1);
                if (end < 0)
                {
                    builder.Append(markup, i, markup.Length - i);
                    break;
                }

                i = end + 1;
                continue;
            }

            builder.Append(c);
            i++;
        }

        return builder.ToString();
    }

    private static int CountWords(string plain)
    {
        var words = 0;
        var inWord = false;

        foreach (var c in plain)
        {
            if (char.IsWhiteSpace(c))
            {
                inWord = false;
                continue;
            }

            if (inWord)
                continue;

            inWord = true;
            words++;
        }

        return words;
    }

    #endregion


/// <summary>
///     The document editor. Formatting is the engine's own markup — the same tags rich text
///     uses everywhere else in the game — so the toolbar is really a tag inserter and the
///     preview is a <see cref="RichTextLabel"/>. That keeps what the player writes portable:
///     a document exported to a file reads the same in Files or in a messenger attachment.
/// </summary>
public sealed class NotesAppUi : IS14OsAppUi
{
    private NotesAppFragment? _fragment;

    private NotesAppFragment Fragment => _fragment ??= new NotesAppFragment();

    public override string AppId => "AppNotes";

    public override Control Root => Fragment;

    public override void Setup(IS14OsBui bui)
    {
        base.Setup(bui);

        Fragment.OnSave += (text, title) => SendAppEvent(AppId, new OsNotesSaveEvent(text, title));
        Fragment.OnExport += name => SendAppEvent(AppId, new OsNotesExportEvent(name));
    }

    public override void UpdateState(IS14OsAppState state)
    {
        if (state is OsNotesState notes)
            Fragment.UpdateState(notes);
    }

    public override void ApplyTheme(IS14ThemePalette palette)
    {
        Fragment.ApplyTheme(palette);
    }
}

[GenerateTypedNameReferences]
public sealed partial class NotesAppFragment : BoxContainer
{
    private const string FontDir = "/Fonts/NotoSans/";
    private const int ToolFontSize = 11;

    /// <summary>Kept in step with the server's cap so the counter can warn before it truncates.</summary>
    private const int MaxLength = 4000;

    /// <summary>Word's palette is a grid; a PDA gets one row. Hex, so the file reads the same anywhere.</summary>
    private static readonly (string Hex, string Loc)[] Swatches =
    {
        ("#E8E8E8", "is14-os-notes-color-default"),
        ("#E05A5A", "is14-os-notes-color-red"),
        ("#E08A3C", "is14-os-notes-color-orange"),
        ("#E0C64B", "is14-os-notes-color-yellow"),
        ("#5FBF6A", "is14-os-notes-color-green"),
        ("#4FC3D9", "is14-os-notes-color-cyan"),
        ("#5A8BE0", "is14-os-notes-color-blue"),
        ("#B173D9", "is14-os-notes-color-purple"),
    };

    [Dependency] private readonly IEntitySystemManager _sysMan = default!;
    [Dependency] private readonly IResourceCache _resource = default!;

    private IS14ThemePalette _palette = IS14ThemePalette.Default;

    private string _saved = string.Empty;
    private string _savedTitle = string.Empty;

    /// <summary>Set while the app writes into the controls itself, so that does not read as an edit.</summary>
    private bool _loading;

    public event Action<string, string>? OnSave;
    public event Action<string>? OnExport;

    public NotesAppFragment()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        VerticalExpand = true;

        var sprites = _sysMan.GetEntitySystem<SpriteSystem>();

        SetupToolbar();
        SetupSwatches();

        TitleEdit.PlaceHolder = Loc.GetString("is14-os-notes-title-placeholder");
        TitleEdit.OnTextChanged += _ => MarkEdited();

        NoteEdit.Placeholder = new Rope.Leaf(Loc.GetString("is14-os-notes-placeholder"));
        NoteEdit.OnTextChanged += _ => MarkEdited();

        SaveButton.Icon = IS14OsStyle.Resolve(sprites, IS14OsStyle.Save);
        SaveButton.Caption = Loc.GetString("is14-os-notes-save");
        SaveButton.OnPressed += _ => Save();

        ExportButton.Icon = IS14OsStyle.Resolve(sprites, IS14OsStyle.Note);
        ExportButton.Caption = Loc.GetString("is14-os-notes-export");
        ExportButton.ToolTip = Loc.GetString("is14-os-notes-export-tooltip");
        ExportButton.OnPressed += _ => OnExport?.Invoke(ExportName());

        Refresh();
    }

    #region Toolbar

    private void SetupToolbar()
    {
        // The buttons wear what they do: bold is bold, italic leans.
        BoldButton.Font = _resource.GetFont(FontDir + "NotoSans-Bold.ttf", ToolFontSize);
        BoldButton.Text = Loc.GetString("is14-os-notes-bold-glyph");
        BoldButton.ToolTip = Loc.GetString("is14-os-notes-bold");
        BoldButton.OnPressed += _ => Wrap("[bold]", "[/bold]");

        ItalicButton.Font = _resource.GetFont(FontDir + "NotoSans-Italic.ttf", ToolFontSize);
        ItalicButton.Text = Loc.GetString("is14-os-notes-italic-glyph");
        ItalicButton.ToolTip = Loc.GetString("is14-os-notes-italic");
        ItalicButton.OnPressed += _ => Wrap("[italic]", "[/italic]");

        SetupHeading(Head1Button, 1);
        SetupHeading(Head2Button, 2);
        SetupHeading(Head3Button, 3);

        BulletButton.Text = Loc.GetString("is14-os-notes-bullet-glyph");
        BulletButton.ToolTip = Loc.GetString("is14-os-notes-bullet");
        BulletButton.OnPressed += _ => InsertBullet();

        ColorButton.Text = Loc.GetString("is14-os-notes-color-glyph");
        ColorButton.ToolTip = Loc.GetString("is14-os-notes-color");
        ColorButton.OnPressed += _ =>
        {
            ColorPanel.Visible = !ColorPanel.Visible;
            ColorButton.Selected = ColorPanel.Visible;
        };

        ClearButton.Text = Loc.GetString("is14-os-notes-clear-glyph");
        ClearButton.ToolTip = Loc.GetString("is14-os-notes-clear");
        ClearButton.OnPressed += _ => ClearFormatting();

        ViewButton.OnPressed += _ => SetPreview(!PreviewPanel.Visible);
        SetPreview(false);
    }

    private void SetupHeading(ToolButton button, int level)
    {
        button.Font = _resource.GetFont(FontDir + "NotoSans-Bold.ttf", ToolFontSize);
        button.Text = Loc.GetString("is14-os-notes-heading-glyph", ("level", level));
        button.ToolTip = Loc.GetString("is14-os-notes-heading", ("level", level));
        button.OnPressed += _ => Wrap($"[head={level}]", "[/head]");
    }

    private void SetupSwatches()
    {
        foreach (var (hex, loc) in Swatches)
        {
            var swatch = new IconTile
            {
                Palette = _palette,
                Compact = true,
                IconSize = 12,
                Swatch = Color.FromHex(hex),
                ToolTip = Loc.GetString(loc),
                Margin = new Thickness(0, 0, 2, 0),
            };

            swatch.OnPressed += _ => Wrap($"[color={hex}]", "[/color]");
            ColorRow.AddChild(swatch);
        }
    }

    private void SetPreview(bool preview)
    {
        PreviewPanel.Visible = preview;
        EditPanel.Visible = !preview;
        ToolbarPanel.Visible = !preview;

        if (!preview)
            ColorPanel.Visible = ColorButton.Selected;
        else
            ColorPanel.Visible = false;

        ViewButton.Text = Loc.GetString(preview ? "is14-os-notes-edit" : "is14-os-notes-preview");
        ViewButton.Selected = preview;

        if (preview)
            UpdatePreview();
    }

    #endregion

    #region Editing

    /// <summary>
    ///     Wraps the selection in a tag pair, or opens an empty one at the caret. Both are what
    ///     a formatting button does in a word processor: with text selected it formats it, with
    ///     nothing selected it turns the style on for whatever gets typed next.
    /// </summary>
    private void Wrap(string open, string close)
    {
        var text = Rope.Collapse(NoteEdit.TextRope);
        var lower = NoteEdit.SelectionLower.Index;
        var upper = NoteEdit.SelectionUpper.Index;
        var selected = text[lower..upper];

        NoteEdit.InsertAtCursor(open + selected + close);

        // Nothing was selected: park the caret between the tags so typing lands inside them.
        if (selected.Length == 0)
            NoteEdit.CursorPosition = new TextEdit.CursorPos(lower + open.Length, TextEdit.LineBreakBias.Top);

        // InsertAtCursor raises OnTextChanged for us, so the status bar is already up to date.
        NoteEdit.GrabKeyboardFocus();
    }

    /// <summary>A bullet belongs at the start of its line, not wherever the caret happens to sit.</summary>
    private void InsertBullet()
    {
        const string bullet = "[bullet]";

        var text = Rope.Collapse(NoteEdit.TextRope);
        var caret = Math.Clamp(NoteEdit.CursorPosition.Index, 0, text.Length);

        var start = 0;
        for (var i = caret - 1; i >= 0; i--)
        {
            if (text[i] != '\n')
                continue;

            start = i + 1;
            break;
        }

        SetText(text.Insert(start, bullet), caret + bullet.Length);
    }

    /// <summary>
    ///     Strips the tags out of the selection, or out of the whole document when there is no
    ///     selection — Word clears formatting the same way.
    /// </summary>
    private void ClearFormatting()
    {
        var text = Rope.Collapse(NoteEdit.TextRope);
        var lower = NoteEdit.SelectionLower.Index;
        var upper = NoteEdit.SelectionUpper.Index;

        if (lower == upper)
        {
            lower = 0;
            upper = text.Length;
        }

        var stripped = Plain(text[lower..upper]);
        SetText(text[..lower] + stripped + text[upper..], lower + stripped.Length);
    }

    private void SetText(string text, int caret)
    {
        NoteEdit.TextRope = new Rope.Leaf(text);
        NoteEdit.CursorPosition = new TextEdit.CursorPos(Math.Clamp(caret, 0, text.Length),
            TextEdit.LineBreakBias.Top);

        NoteEdit.GrabKeyboardFocus();
        MarkEdited();
    }

    private void Save()
    {
        _saved = Rope.Collapse(NoteEdit.TextRope);
        _savedTitle = TitleEdit.Text.Trim();

        SavedLabel.Text = Loc.GetString("is14-os-notes-saved");
        SavedLabel.FontColorOverride = _palette.Good;

        OnSave?.Invoke(_saved, _savedTitle);
    }

    /// <summary>The document's name, falling back to its first words the way a new file does.</summary>
    private string ExportName()
    {
        var title = TitleEdit.Text.Trim();
        if (title.Length > 0)
            return title;

        var plain = Plain(Rope.Collapse(NoteEdit.TextRope));
        return plain.Split('\n')[0].Trim();
    }

    #endregion

    #region State

    private void MarkEdited()
    {
        if (_loading)
            return;

        var dirty = Rope.Collapse(NoteEdit.TextRope) != _saved || TitleEdit.Text.Trim() != _savedTitle;

        if (dirty)
        {
            SavedLabel.Text = Loc.GetString("is14-os-notes-unsaved");
            SavedLabel.FontColorOverride = _palette.Warn;
        }

        Refresh();
    }

    /// <summary>Status bar and, when it is showing, the rendered page.</summary>
    private void Refresh()
    {
        var text = Rope.Collapse(NoteEdit.TextRope);
        var plain = Plain(text);

        CountLabel.Text = Loc.GetString("is14-os-notes-count",
            ("words", CountWords(plain)),
            ("chars", text.Length),
            ("max", MaxLength));

        // The server truncates past the cap, so say so before it happens rather than after.
        CountLabel.FontColorOverride = text.Length > MaxLength ? _palette.Bad : _palette.Muted;

        if (PreviewPanel.Visible)
            UpdatePreview();
    }

    private void UpdatePreview()
    {
        var text = Rope.Collapse(NoteEdit.TextRope);

        FormattedMessage message;
        try
        {
            message = FormattedMessage.FromMarkupPermissive(text);
        }
        catch (Exception)
        {
            // Half-typed markup is normal in an editor: show it as plain text rather than
            // letting a parse error take the app down.
            message = FormattedMessage.FromUnformatted(text);
        }

        PreviewText.SetMessage(message, _palette.Text);
    }

    public void UpdateState(OsNotesState state)
    {
        if (state.Status != null)
        {
            SavedLabel.Text = Loc.GetString(state.Status);
            SavedLabel.FontColorOverride = _palette.Good;
        }

        // Don't stomp on what the player is typing: only take the server's copy when it is
        // genuinely different from what we last sent.
        if (state.Text == _saved && state.Title == _savedTitle)
            return;

        _loading = true;

        _saved = state.Text;
        _savedTitle = state.Title;

        NoteEdit.TextRope = new Rope.Leaf(state.Text);
        TitleEdit.Text = state.Title;

        if (state.Status == null)
            SavedLabel.Text = string.Empty;

        _loading = false;

        Refresh();
    }

    #endregion

    #region Markup

    /// <summary>
    ///     The text without its tags. Used for the word count and for clearing formatting, so
    ///     it has to survive half-written markup: a bracket with no closing one is text.
    /// </summary>
    private static string Plain(string markup)
    {
        var builder = new StringBuilder(markup.Length);

        var i = 0;
        while (i < markup.Length)
        {
            var c = markup[i];

            if (c == '\\' && i + 1 < markup.Length)
            {
                builder.Append(markup[i + 1]);
                i += 2;
                continue;
            }

            if (c == '[')
            {
                var end = markup.IndexOf(']', i + 1);
                if (end < 0)
                {
                    builder.Append(markup, i, markup.Length - i);
                    break;
                }

                i = end + 1;
                continue;
            }

            builder.Append(c);
            i++;
        }

        return builder.ToString();
    }

    private static int CountWords(string plain)
    {
        var words = 0;
        var inWord = false;

        foreach (var c in plain)
        {
            if (char.IsWhiteSpace(c))
            {
                inWord = false;
                continue;
            }

            if (inWord)
                continue;

            inWord = true;
            words++;
        }

        return words;
    }

    #endregion

    public void ApplyTheme(IS14ThemePalette palette)
    {
        _palette = palette;

        SavedLabel.FontColorOverride = palette.Good;
        CountLabel.FontColorOverride = palette.Muted;

        SaveButton.Palette = palette;
        ExportButton.Palette = palette;

        BoldButton.Palette = palette;
        ItalicButton.Palette = palette;
        Head1Button.Palette = palette;
        Head2Button.Palette = palette;
        Head3Button.Palette = palette;
        BulletButton.Palette = palette;
        ColorButton.Palette = palette;
        ClearButton.Palette = palette;
        ViewButton.Palette = palette;

        foreach (var child in ColorRow.Children)
        {
            if (child is IconTile swatch)
                swatch.Palette = palette;
        }

        var ribbon = new StyleBoxFlat
        {
            BackgroundColor = palette.PanelRaised,
            BorderColor = palette.Border,
            BorderThickness = new Thickness(1),
        };

        ToolbarPanel.PanelOverride = ribbon;
        ColorPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = palette.PanelRaised,
            BorderColor = palette.Border,
            BorderThickness = new Thickness(1),
        };

        var page = new StyleBoxFlat
        {
            BackgroundColor = palette.Backdrop,
            BorderColor = palette.Border,
            BorderThickness = new Thickness(1),
            ContentMarginLeftOverride = 4,
            ContentMarginRightOverride = 4,
            ContentMarginTopOverride = 3,
            ContentMarginBottomOverride = 3,
        };

        EditPanel.PanelOverride = page;
        PreviewPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = palette.Backdrop,
            BorderColor = palette.Border,
            BorderThickness = new Thickness(1),
        };

        TitleEdit.StyleBoxOverride = new StyleBoxFlat
        {
            BackgroundColor = palette.Panel,
            BorderColor = palette.Border,
            BorderThickness = new Thickness(1),
            ContentMarginLeftOverride = 4,
            ContentMarginRightOverride = 4,
            ContentMarginTopOverride = 2,
            ContentMarginBottomOverride = 2,
        };

        Refresh();
    }
}

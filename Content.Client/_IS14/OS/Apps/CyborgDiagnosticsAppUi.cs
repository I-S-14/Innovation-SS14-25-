namespace Content.Client._IS14.OS.Apps;

/// <summary>
///     Cyborg self-diagnosis, tg's RoboTact: a status report of the chassis the tablet is built into.
/// </summary>
public sealed class CyborgDiagnosticsAppUi : IS14OsAppUi
{
    private CyborgDiagnosticsAppFragment? _fragment;

    private CyborgDiagnosticsAppFragment Fragment => _fragment ??= new CyborgDiagnosticsAppFragment();

    public override string AppId => "IS14AppCyborgDiagnostics";

    public override Control Root => Fragment;

    public override void UpdateState(IS14OsAppState state)
    {
        if (state is OsCyborgDiagnosticsState diagnostics)
            Fragment.UpdateState(diagnostics);
    }

    public override void ApplyTheme(IS14ThemePalette palette)
    {
    }
}

[GenerateTypedNameReferences]
public sealed partial class CyborgDiagnosticsAppFragment : BoxContainer
{
    public CyborgDiagnosticsAppFragment()
    {
        RobustXamlLoader.Load(this);
        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        VerticalExpand = true;
    }

    public void UpdateState(OsCyborgDiagnosticsState s)
    {
        if (!s.IsCyborg)
        {
            Report.SetMessage(Loc.GetString("cyborg-diag-not-cyborg"));
            return;
        }

        var none = Loc.GetString("cyborg-diag-none");
        var sb = new StringBuilder();
        sb.AppendLine(Loc.GetString("cyborg-diag-model", ("value", s.Model ?? none)));
        sb.AppendLine(Loc.GetString("cyborg-diag-charge",
            ("value", s.Charge is { } c ? $"{(int) MathF.Round(c * 100)}%" : none)));
        sb.AppendLine(Loc.GetString("cyborg-diag-integrity", ("value", (int) MathF.Round(s.Integrity * 100))));
        sb.AppendLine(Loc.GetString("cyborg-diag-slots", ("working", s.Slots - s.BrokenSlots), ("total", s.Slots)));
        sb.AppendLine(Loc.GetString("cyborg-diag-ai", ("value", s.Ai ?? none)));
        sb.AppendLine(Loc.GetString(s.LawSync ? "cyborg-diag-lawsync-on" : "cyborg-diag-lawsync-off"));
        if (s.Lockdown)
            sb.AppendLine(Loc.GetString("cyborg-diag-lockdown"));
        if (s.Emagged)
            sb.AppendLine(Loc.GetString("cyborg-diag-emagged"));
        sb.AppendLine();
        sb.AppendLine(Loc.GetString("cyborg-diag-laws"));
        foreach (var law in s.Laws)
            sb.AppendLine(law);
        sb.AppendLine();
        sb.AppendLine(Loc.GetString("cyborg-diag-upgrades",
            ("value", s.Upgrades.Count > 0 ? string.Join(", ", s.Upgrades) : none)));

        Report.SetMessage(sb.ToString().TrimEnd());
    }
}

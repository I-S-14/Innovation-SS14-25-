using Content.Client.Options.UI;
using Content.Shared._IS14.CCVar;
using Content.Shared._IS14.Paper;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._IS14.Options.UI.Tabs;

/// <summary>
///     Options that belong to Innovation Station rather than upstream, kept on their own tab so
///     upstream tabs stay untouched.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class IS14Tab : Control
{
    /// <summary>
    ///     The slider is capped at the steepest angle the server will accept for a stamp, so it
    ///     can never ask for a tilt that would just be clamped away on placement.
    /// </summary>
    private static readonly int MaxTiltDegrees =
        (int) MathF.Round(StampPlacementSystem.MaxRotation * 180.0f / MathF.PI);

    public IS14Tab()
    {
        RobustXamlLoader.Load(this);

        Control.AddOptionCheckBox(IS14CVars.StampRandomTilt, StampRandomTiltCheckBox);
        Control.AddOptionSlider(IS14CVars.StampMaxTilt, StampMaxTiltSlider, 0, MaxTiltDegrees, FormatDegrees);

        Control.Initialize();
    }

    private static string FormatDegrees(OptionSliderIntCVar option, int value)
    {
        return Loc.GetString("ui-options-is14-stamp-max-tilt-value", ("degrees", value));
    }
}

using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._IS14.Economy.VendingMachine;

/// <summary>
/// Tab button for the vending machine window: a label plus an optional
/// lock icon shown when the viewer lacks access to the tab.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class IS14VendingTabButton : ContainerButton
{
    public IS14VendingTabButton()
    {
        RobustXamlLoader.Load(this);
    }

    public string? Text
    {
        get => TabLabel.Text;
        set => TabLabel.Text = value;
    }

    public bool Locked
    {
        get => LockIcon.Visible;
        set => LockIcon.Visible = value;
    }

    public Color? TextColor
    {
        get => TabLabel.FontColorOverride;
        set => TabLabel.FontColorOverride = value;
    }
}

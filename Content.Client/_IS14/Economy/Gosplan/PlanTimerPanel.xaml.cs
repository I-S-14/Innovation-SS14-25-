using Content.Shared._IS14.Economy.Gosplan;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._IS14.Economy.Gosplan;

/// <summary>
/// Period number and the countdown to the next scoring. The server only sends state
/// once a second, so the panel runs its own clock between updates — a board that
/// ticks smoothly reads as a live instrument rather than a refreshing web page.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PlanTimerPanel : BoxContainer
{
    /// <summary>Below this the countdown turns red and the scale starts breathing.</summary>
    private const float UrgentSeconds = 60f;

    /// <summary>Below this the countdown warns in amber.</summary>
    private const float WarnSeconds = 180f;

    private static readonly Color Calm = GosplanPalette.Gold;
    private static readonly Color Warn = Color.FromHex("#E09A40");
    private static readonly Color Urgent = Color.FromHex("#E05050");

    private readonly StyleBoxFlat _timerBox = new()
    {
        BackgroundColor = Color.FromHex("#070A14"),
        BorderThickness = new Thickness(1),
    };

    private float _secondsLeft;
    private float _periodSeconds = 1f;
    private bool _active;

    /// <summary>Last whole second rendered, so the labels aren't rebuilt every frame.</summary>
    private int _shownSecond = -1;

    public PlanTimerPanel()
    {
        RobustXamlLoader.Load(this);

        TimerBox.PanelOverride = _timerBox;

        // The period scale is a plain elapsed bar — no target or failure lines on it.
        PeriodGauge.Target = null;
        PeriodGauge.Fail = null;
        PeriodGauge.FillColor = GosplanPalette.GoldDim;
        PeriodGauge.OverColor = GosplanPalette.GoldDim;
    }

    public void Update(GosplanConsoleUiState state)
    {
        _active = state.Active;

        if (!_active)
        {
            PeriodLabel.Text = Loc.GetString("is14-gosplan-no-plan");
            PeriodLabel.FontColorOverride = GosplanPalette.TextDim;
            TimerLabel.Text = "--:--";
            TimerLabel.FontColorOverride = GosplanPalette.TextDim;
            _timerBox.BorderColor = GosplanPalette.Border;
            TimerCaptionLabel.Text = string.Empty;
            ElapsedLabel.Text = string.Empty;
            QuotaCountLabel.Text = string.Empty;
            PeriodGauge.Value = 0f;
            PeriodGauge.Pulse = false;
            return;
        }

        PeriodLabel.Text = Loc.GetString("is14-gosplan-period", ("period", state.PeriodIndex));
        PeriodLabel.FontColorOverride = GosplanPalette.Gold;
        QuotaCountLabel.Text = Loc.GetString("is14-gosplan-quota-count",
            ("count", state.QuotaCount),
            ("departments", state.Departments.Count));

        _periodSeconds = MathF.Max(1f, state.PeriodSeconds);
        _secondsLeft = Math.Clamp(state.SecondsLeft, 0f, _periodSeconds);
        _shownSecond = -1;

        Refresh();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!_active)
            return;

        _secondsLeft = MathF.Max(0f, _secondsLeft - args.DeltaSeconds);
        Refresh();
    }

    private void Refresh()
    {
        var elapsed = Math.Clamp(1f - _secondsLeft / _periodSeconds, 0f, 1f);
        var urgent = _secondsLeft <= UrgentSeconds;

        PeriodGauge.Value = elapsed;
        PeriodGauge.Pulse = urgent;
        PeriodGauge.FillColor = urgent ? Urgent.WithAlpha(0.8f) : GosplanPalette.GoldDim;
        PeriodGauge.OverColor = PeriodGauge.FillColor;

        var whole = (int)MathF.Ceiling(_secondsLeft);
        if (whole == _shownSecond)
            return;

        _shownSecond = whole;

        var clockColor = urgent ? Urgent : _secondsLeft <= WarnSeconds ? Warn : Calm;

        TimerLabel.Text = FormatClock(whole);
        TimerLabel.FontColorOverride = clockColor;
        _timerBox.BorderColor = clockColor.WithAlpha(0.7f);

        TimerCaptionLabel.Text = whole <= 0
            ? Loc.GetString("is14-gosplan-timer-scoring")
            : Loc.GetString("is14-gosplan-timer-caption");

        ElapsedLabel.Text = Loc.GetString("is14-gosplan-elapsed",
            ("percent", (int)MathF.Round(elapsed * 100f)));
    }

    private static string FormatClock(int seconds)
    {
        var span = TimeSpan.FromSeconds(seconds);

        return span.TotalHours >= 1
            ? $"{(int)span.TotalHours}:{span.Minutes:00}:{span.Seconds:00}"
            : $"{(int)span.TotalMinutes:00}:{span.Seconds:00}";
    }
}

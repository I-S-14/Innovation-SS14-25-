using Content.Shared._IS14.Economy.Gosplan;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._IS14.Economy.Gosplan;

/// <summary>
/// One closed period in the history tab. Each period is a card of its own — the tab
/// used to be a wall of coloured lines where nobody could tell where one period
/// ended and the next began.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PlanPeriodCard : BoxContainer
{
    private static readonly Color CardBackground = Color.FromHex("#1B2138");
    private static readonly Color LatestBackground = Color.FromHex("#232B47");
    private static readonly Color LeaderText = Color.FromHex("#E0C060");

    private readonly StyleBoxFlat _cardPanel = new()
    {
        BackgroundColor = CardBackground,
        BorderThickness = new Thickness(3, 1, 1, 1),
    };

    private readonly StyleBoxFlat _badgePanel = new()
    {
        BorderThickness = new Thickness(1),
    };

    public PlanPeriodCard()
    {
        RobustXamlLoader.Load(this);

        CardPanel.PanelOverride = _cardPanel;
        PeriodBadge.PanelOverride = _badgePanel;
        Gauge.Segments = 15;
    }

    public void Update(PlanPeriodEntry period, GosplanConsoleUiState state, bool latest)
    {
        var color = GosplanPalette.ForFulfillment(period.AverageFulfillment, state.FailThreshold, state.OverThreshold);

        _cardPanel.BackgroundColor = latest ? LatestBackground : CardBackground;
        _cardPanel.BorderColor = latest ? color : color.WithAlpha(0.55f);

        _badgePanel.BackgroundColor = color.WithAlpha(0.16f);
        _badgePanel.BorderColor = color.WithAlpha(0.65f);

        PeriodLabel.Text = Loc.GetString("is14-gosplan-history-badge", ("period", period.PeriodIndex));
        PeriodLabel.FontColorOverride = color;

        LatestLabel.Visible = latest;
        LatestLabel.Text = Loc.GetString("is14-gosplan-history-latest");

        var percent = (int)MathF.Round(period.AverageFulfillment * 100f);
        AverageLabel.Text = Loc.GetString("is14-gosplan-percent", ("percent", percent));
        AverageLabel.FontColorOverride = color;

        AverageCaptionLabel.Text = Loc.GetString("is14-gosplan-history-average");

        Gauge.MaxValue = MathF.Max(state.PayoutCap, state.OverThreshold * 1.1f);
        Gauge.Target = state.OverThreshold;
        Gauge.Fail = state.FailThreshold;
        Gauge.Value = period.AverageFulfillment;
        Gauge.FillColor = color;

        PayoutLabel.Text = Loc.GetString("is14-gosplan-history-payout", ("payout", period.TotalPayout));
        PayoutLabel.FontColorOverride = GosplanPalette.GoldDim;

        LeaderLabel.Visible = period.LeaderFundName.Length > 0;
        if (LeaderLabel.Visible)
        {
            LeaderLabel.Text = GosplanPalette.Markup(LeaderText,
                Loc.GetString("is14-gosplan-history-leader", ("fund", period.LeaderFundName)));
        }

        FailedLabel.Visible = period.FailedFunds.Count > 0;
        if (FailedLabel.Visible)
        {
            FailedLabel.Text = GosplanPalette.Markup(GosplanPalette.Failing,
                Loc.GetString("is14-gosplan-history-failed",
                    ("funds", string.Join(", ", period.FailedFunds))));
        }
    }
}

using Content.Shared._IS14.Economy.Gosplan;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._IS14.Economy.Gosplan;

/// <summary>
/// Header of the selected department. The metrics below it are each scored on their
/// own, so this panel carries the one figure that decides the department's fate: the
/// mean, which is what the banner, the fail streak and the sanctions all read.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PlanDepartmentPanel : BoxContainer
{
    private readonly StyleBoxFlat _headerPanel = new()
    {
        BackgroundColor = Color.FromHex("#141A2C"),
        BorderThickness = new Thickness(3, 0, 0, 0),
    };

    public PlanDepartmentPanel()
    {
        RobustXamlLoader.Load(this);

        HeaderPanel.PanelOverride = _headerPanel;
    }

    public void Update(PlanDepartmentEntry entry, GosplanConsoleUiState state)
    {
        var fundColor = GosplanPalette.Fund(entry.FundId);
        var color = GosplanPalette.ForFulfillment(entry.Fulfillment, state.FailThreshold, state.OverThreshold);

        _headerPanel.BorderColor = fundColor;

        NameLabel.Text = entry.FundName;
        NameLabel.FontColorOverride = fundColor;

        BannerLabel.Visible = entry.HasBanner;
        BannerLabel.Text = Loc.GetString("is14-gosplan-department-banner");
        BannerLabel.FontColorOverride = GosplanPalette.Gold;

        PercentLabel.Text = Loc.GetString("is14-gosplan-percent",
            ("percent", (int)MathF.Round(entry.Fulfillment * 100f)));
        PercentLabel.FontColorOverride = color;

        // Spelling out what the headline number is stops it reading as another metric.
        CaptionLabel.Text = Loc.GetString("is14-gosplan-department-caption", ("count", entry.Quotas.Count));
        CaptionLabel.FontColorOverride = GosplanPalette.TextDim;

        Gauge.MaxValue = MathF.Max(state.PayoutCap, state.OverThreshold * 1.1f);
        Gauge.Target = state.OverThreshold;
        Gauge.Fail = state.FailThreshold;
        Gauge.Value = entry.Fulfillment;
        Gauge.FillColor = color;
        Gauge.Pulse = entry.FailStreak > 0 && entry.Fulfillment < state.FailThreshold;

        StatusLabel.Text = GetStatus(entry, state);
        StatusLabel.FontColorOverride = color;

        PayoutLabel.Text = Loc.GetString("is14-gosplan-payout-line",
            ("current", entry.ProjectedPayout),
            ("full", entry.FullPayout));
        PayoutLabel.FontColorOverride = GosplanPalette.GoldDim;

        LastLabel.Text = entry.LastFulfillment is { } last
            ? Loc.GetString("is14-gosplan-note-last", ("percent", (int)MathF.Round(last * 100f)))
            : string.Empty;

        LastLabel.FontColorOverride = GosplanPalette.TextDim;

        WarningLabel.Visible = entry.FailStreak > 0;
        if (entry.FailStreak > 0)
        {
            WarningLabel.Text = GosplanPalette.Markup(GosplanPalette.Failing,
                Loc.GetString("is14-gosplan-note-warning", ("streak", entry.FailStreak)));
        }
    }

    private static string GetStatus(PlanDepartmentEntry entry, GosplanConsoleUiState state)
    {
        if (entry.Fulfillment >= state.OverThreshold)
            return Loc.GetString("is14-gosplan-status-over");

        if (entry.Fulfillment < state.FailThreshold)
            return Loc.GetString("is14-gosplan-status-failing");

        return Loc.GetString("is14-gosplan-status-ontrack");
    }
}

using Content.Shared._IS14.Economy.Treasury;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._IS14.Economy.Treasury;

[GenerateTypedNameReferences]
public sealed partial class TreasuryConsoleWindow : DefaultWindow
{
    /// <summary>Fired when the user requests a transfer: (target account proto ID, amount).</summary>
    public event Action<string, int>? OnTransfer;

    /// <summary>Non-treasury account proto IDs in selector order.</summary>
    private readonly List<string> _targets = new();

    public TreasuryConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        Add1KBtn.OnPressed += _ => AddAmount(1000);
        Add5KBtn.OnPressed += _ => AddAmount(5000);
        Add10KBtn.OnPressed += _ => AddAmount(10000);

        TargetSelector.OnItemSelected += args => TargetSelector.SelectId(args.Id);

        TransferBtn.OnPressed += _ => SubmitTransfer();
        AmountEdit.OnTextEntered += _ => SubmitTransfer();
    }

    public void UpdateState(TreasuryConsoleUiState state)
    {
        AccountsList.RemoveAllChildren();

        var selectedTarget = TargetSelector.SelectedId >= 0 && TargetSelector.SelectedId < _targets.Count
            ? _targets[TargetSelector.SelectedId]
            : null;

        _targets.Clear();
        TargetSelector.Clear();

        foreach (var account in state.Accounts)
        {
            if (account.IsTreasury)
            {
                TreasuryBalanceLabel.Text = Loc.GetString("is14-treasury-credits", ("amount", account.Balance));
                continue;
            }

            AccountsList.AddChild(MakeAccountRow(account));

            TargetSelector.AddItem(account.DisplayName, _targets.Count);
            if (account.ProtoId == selectedTarget)
                TargetSelector.SelectId(_targets.Count);
            _targets.Add(account.ProtoId);
        }

        if (state.Status.Length > 0)
            StatusLabel.Text = state.Status;
    }

    private Control MakeAccountRow(TreasuryAccountEntry account)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(0, 2),
        };

        row.AddChild(new Label
        {
            Text = account.DisplayName,
            HorizontalExpand = true,
            FontColorOverride = Color.FromHex("#B8C4D8"),
        });

        row.AddChild(new Label
        {
            Text = Loc.GetString("is14-treasury-credits", ("amount", account.Balance)),
            FontColorOverride = Color.FromHex("#3ABB3A"),
        });

        return row;
    }

    private void AddAmount(int delta)
    {
        int.TryParse(AmountEdit.Text, out var current);
        AmountEdit.Text = (current + delta).ToString();
    }

    private void SubmitTransfer()
    {
        if (TargetSelector.SelectedId < 0 || TargetSelector.SelectedId >= _targets.Count)
            return;

        if (!int.TryParse(AmountEdit.Text, out var amount) || amount <= 0)
            return;

        OnTransfer?.Invoke(_targets[TargetSelector.SelectedId], amount);
        AmountEdit.Text = string.Empty;
    }
}

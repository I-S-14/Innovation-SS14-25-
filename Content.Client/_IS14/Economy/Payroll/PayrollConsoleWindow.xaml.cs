using Content.Shared._IS14.Economy.Payroll;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._IS14.Economy.Payroll;

/// <summary>
///     The standalone payroll console: a window around <see cref="PayrollConsolePanel"/>.
///     The layout itself lives in the panel so the OS application can show the same thing
///     without a window around it (Docs/_IS14/os-design.md §12.2).
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PayrollConsoleWindow : DefaultWindow
{
    /// <summary>Fired when the head applies a new recurring salary: (employee, salary).</summary>
    public event Action<NetEntity, int>? OnSetSalary;

    /// <summary>Fired when the head pays a bonus: (employee, amount).</summary>
    public event Action<NetEntity, int>? OnBonus;

    /// <summary>Fired when the head issues a fine: (employee, amount).</summary>
    public event Action<NetEntity, int>? OnFine;

    public PayrollConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        Panel.OnSetSalary += (employee, salary) => OnSetSalary?.Invoke(employee, salary);
        Panel.OnBonus += (employee, amount) => OnBonus?.Invoke(employee, amount);
        Panel.OnFine += (employee, amount) => OnFine?.Invoke(employee, amount);
    }

    public void UpdateState(PayrollConsoleUiState state)
    {
        Panel.UpdateState(state);
    }
}

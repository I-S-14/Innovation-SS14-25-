using Content.Shared._IS14.Economy.Payroll;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._IS14.Economy.Payroll;

[GenerateTypedNameReferences]
public sealed partial class PayrollConsoleWindow : DefaultWindow
{
    private const int PayrollTab = 0;
    private const int LogTab = 1;

    private static readonly Color ColorLogTime     = Color.FromHex("#5A6478");
    private static readonly Color ColorLogPositive = Color.FromHex("#3ABB3A");
    private static readonly Color ColorLogNegative = Color.FromHex("#BF8A40");
    private static readonly Color ColorLogDenied   = Color.FromHex("#993030");

    /// <summary>Fired when the head applies a new recurring salary: (employee, salary).</summary>
    public event Action<NetEntity, int>? OnSetSalary;

    /// <summary>Fired when the head pays a bonus: (employee, amount).</summary>
    public event Action<NetEntity, int>? OnBonus;

    /// <summary>Fired when the head issues a fine: (employee, amount).</summary>
    public event Action<NetEntity, int>? OnFine;

    private readonly Dictionary<NetEntity, PayrollEmployeeRow> _rows = new();

    private NetEntity? _selected;
    private PayrollEmployeeEntry? _selectedEntry;

    public PayrollConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        Tabs.SetTabTitle(PayrollTab, Loc.GetString("is14-payroll-tab-payroll"));
        Tabs.SetTabTitle(LogTab, Loc.GetString("is14-payroll-tab-log"));

        SalaryMinusBtn.OnPressed += _ => StepSalary(-50);
        SalaryPlusBtn.OnPressed += _ => StepSalary(50);

        SalaryApplyBtn.OnPressed += _ => SubmitSalary();
        SalaryEdit.OnTextEntered += _ => SubmitSalary();

        BonusBtn.OnPressed += _ => SubmitOneOff(OnBonus);
        FineBtn.OnPressed += _ => SubmitOneOff(OnFine);

        UpdateSelectionControls();
    }

    public void UpdateState(PayrollConsoleUiState state)
    {
        FundNameLabel.Text = state.FundName;
        FundBalanceLabel.Text = Loc.GetString("is14-payroll-credits", ("amount", state.FundBalance));

        EmployeeList.RemoveAllChildren();
        _rows.Clear();
        _selectedEntry = null;

        foreach (var entry in state.Employees)
        {
            var row = new PayrollEmployeeRow();
            row.Initialize(entry);
            row.OnPressed += _ => Select(entry);

            EmployeeList.AddChild(row);
            _rows[entry.Employee] = row;

            if (entry.Employee == _selected)
                _selectedEntry = entry;
        }

        // The previously selected employee may have left the payroll entirely.
        if (_selectedEntry == null)
            _selected = null;

        LimitsLabel.Text = Loc.GetString("is14-payroll-limits",
            ("pool", state.BonusPool),
            ("bonus", state.MaxBonus),
            ("fine", state.MaxFine));

        RefreshSelectionHighlight();
        UpdateSelectionControls();
        UpdateLog(state.Log);

        if (state.Status.Length > 0)
            StatusLabel.Text = state.Status;
    }

    private void UpdateLog(List<PayrollLogEntry> log)
    {
        LogList.RemoveAllChildren();
        LogEmptyLabel.Visible = log.Count == 0;

        foreach (var entry in log)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(0, 1),
            };

            row.AddChild(new Label
            {
                Text = FormatTime(entry.Timestamp),
                SetWidth = 70,
                FontColorOverride = ColorLogTime,
            });

            row.AddChild(new Label
            {
                Text = entry.Message,
                HorizontalExpand = true,
                FontColorOverride = entry.Kind switch
                {
                    PayrollLogKind.Positive => ColorLogPositive,
                    PayrollLogKind.Negative => ColorLogNegative,
                    _ => ColorLogDenied,
                },
            });

            LogList.AddChild(row);
        }
    }

    private static string FormatTime(TimeSpan ts)
        => $"{(int)ts.TotalHours:D2}:{ts.Minutes:D2}:{ts.Seconds:D2}";

    private void Select(PayrollEmployeeEntry entry)
    {
        _selected = entry.Employee;
        _selectedEntry = entry;

        SalaryEdit.Text = entry.Salary.ToString();

        RefreshSelectionHighlight();
        UpdateSelectionControls();
    }

    private void RefreshSelectionHighlight()
    {
        foreach (var (employee, row) in _rows)
        {
            row.SetSelected(employee == _selected);
        }
    }

    private void UpdateSelectionControls()
    {
        var entry = _selectedEntry;

        SalaryEdit.Editable = entry != null;
        SalaryMinusBtn.Disabled = entry == null;
        SalaryPlusBtn.Disabled = entry == null;
        SalaryApplyBtn.Disabled = entry == null;
        AmountEdit.Editable = entry != null;
        BonusBtn.Disabled = entry == null;
        FineBtn.Disabled = entry == null;

        if (entry == null)
        {
            SelectionLabel.Text = Loc.GetString("is14-payroll-no-selection");
            SelectionHintLabel.Text = string.Empty;
            SalaryEdit.Text = string.Empty;
            return;
        }

        SelectionLabel.Text = Loc.GetString("is14-payroll-selection", ("name", entry.Name), ("job", entry.JobTitle));
        SelectionHintLabel.Text = Loc.GetString("is14-payroll-selection-hint",
            ("base", entry.BaseSalary),
            ("min", entry.MinSalary),
            ("max", entry.MaxSalary));
    }

    private void StepSalary(int delta)
    {
        if (_selectedEntry is not { } entry)
            return;

        int.TryParse(SalaryEdit.Text, out var current);
        SalaryEdit.Text = Math.Clamp(current + delta, entry.MinSalary, entry.MaxSalary).ToString();
    }

    private void SubmitSalary()
    {
        if (_selected is not { } employee || _selectedEntry == null)
            return;

        if (!int.TryParse(SalaryEdit.Text, out var salary) || salary < 0)
            return;

        OnSetSalary?.Invoke(employee, salary);
    }

    private void SubmitOneOff(Action<NetEntity, int>? action)
    {
        if (_selected is not { } employee)
            return;

        if (!int.TryParse(AmountEdit.Text, out var amount) || amount <= 0)
            return;

        action?.Invoke(employee, amount);
        AmountEdit.Text = string.Empty;
    }
}

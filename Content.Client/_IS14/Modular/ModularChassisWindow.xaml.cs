    private void UpdateDetail(ModularChassisUiState state)
    {
        DetailContainer.RemoveAllChildren();

        if (!_hardwareSelected)
        {
            var part = state.Parts.FirstOrDefault(p => p.Part == _selectedPart);

            if (part != null)
            {
                BuildPartDetail(part, state);
                return;
            }

            // The part went away — fall back rather than leaving a blank panel.
            _hardwareSelected = true;
            _selectedPart = null;
        }

        BuildHardwareDetail(state);
    }

    private void BuildPartDetail(ChassisPartUiEntry part, ModularChassisUiState state)
    {
        DetailContainer.AddChild(ChassisStyle.Heading(part.Name));

        DetailContainer.AddChild(ChassisStyle.Sub(Loc.GetString(PartStateLocId(part)), PartColor(part)));
        DetailContainer.AddChild(ChassisStyle.Rule());

        BuildIntegrityBlock(part);
        DetailContainer.AddChild(ChassisStyle.Rule());

        var id = part.Part;

        // A sealed piece is welded shut; unseal it before anything folds away.
        var deploy = ChassisButton.Make(
            UiIcon(part.Sealed ? IconNo : part.Deployed ? IconRetract : IconDeploy),
            Loc.GetString(part.Deployed ? "chassis-ui-retract" : "chassis-ui-deploy"),
            part.Deployed ? ChassisStyle.Warn : ChassisStyle.Accent);

        deploy.HorizontalExpand = true;
        deploy.Margin = new Thickness(0, 0, 0, 4);
        deploy.Disabled = part.Sealed;
        deploy.OnPressed += _ => OnTogglePart?.Invoke(id);
        DetailContainer.AddChild(deploy);

        var canSeal = part.Deployed && (part.Sealed || !part.Ruptured);

        var seal = ChassisButton.Make(
            UiIcon(!canSeal ? IconNo : part.Sealed ? IconUnseal : IconSeal),
            Loc.GetString(part.Sealed ? "chassis-ui-unseal" : "chassis-ui-seal"),
            part.Sealed ? ChassisStyle.Good : ChassisStyle.Accent);

        seal.HorizontalExpand = true;
        seal.Selected = part.Sealed;
        seal.Disabled = !canSeal;
        seal.OnPressed += _ => OnSealPart?.Invoke(id);
        DetailContainer.AddChild(seal);

        if (!part.Deployed)
            DetailContainer.AddChild(ChassisStyle.Sub(Loc.GetString("chassis-ui-part-hint-deploy")));
        else if (state.MaxCharge <= 0f)
            DetailContainer.AddChild(ChassisStyle.Sub(NoChargeReason(state), ChassisStyle.Bad));
    }

    /// <summary>
    ///     Plating condition, with the consequence spelled out rather than left to the
    ///     player to infer from a bar that has gone red.
    /// </summary>
    private void BuildIntegrityBlock(ChassisPartUiEntry part)
    {
        var fraction = Fraction(part);
        var bar = new IntegrityBar
        {
            Fraction = fraction,
            ModuleThreshold = part.ModuleThreshold,
            UnsealThreshold = part.UnsealThreshold,
            MinHeight = 8,
            HorizontalExpand = true,
        };

        var header = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };

        var glyph = ChassisStyle.Icon(UiIcon(part.Broken ? IconNo : IconShield), 16f, bar.FillColor);
        glyph.Margin = new Thickness(0, 0, 6, 0);
        header.AddChild(glyph);

        header.AddChild(new Label
        {
            Text = Loc.GetString("chassis-ui-integrity"),
            HorizontalExpand = true,
            StyleClasses = { "LabelSubText" },
        });

        header.AddChild(new Label
        {
            Text = Loc.GetString(
                "chassis-ui-integrity-value",
                ("current", (int) MathF.Round(part.Integrity)),
                ("max", (int) MathF.Round(part.MaxIntegrity))),
            FontColorOverride = bar.FillColor,
        });

        DetailContainer.AddChild(header);
        DetailContainer.AddChild(bar);

        // The two thresholds spelled out as the two things the piece is for, rather than
        // as a sentence the player has to translate back into consequences.
        DetailContainer.AddChild(StatusRow("chassis-ui-status-seal", !part.Ruptured));
        DetailContainer.AddChild(StatusRow("chassis-ui-status-modules", !part.Broken));

        if (part.Fault == ChassisPartFault.None)
            return;

        var fix = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(0, 5, 0, 0),
        };

        var hammer = ChassisStyle.Icon(UiIcon(IconHammer), 16f, ChassisStyle.Accent);
        hammer.Margin = new Thickness(0, 0, 6, 0);
        fix.AddChild(hammer);

        fix.AddChild(new Label
        {
            Text = Loc.GetString(part.Fault == ChassisPartFault.Electrical
                ? "chassis-ui-fault-electrical"
                : "chassis-ui-fault-structural"),
            HorizontalExpand = true,
            StyleClasses = { "LabelSubText" },
            FontColorOverride = ChassisStyle.Accent,
        });

        DetailContainer.AddChild(fix);
    }


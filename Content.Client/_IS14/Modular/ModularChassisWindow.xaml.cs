    private void UpdateDoll(ModularChassisUiState state)
    {
        DollGrid.RemoveAllChildren();
        ExtraPartsContainer.RemoveAllChildren();

        var bySlot = new Dictionary<string, ChassisPartUiEntry>();
        var extras = new List<ChassisPartUiEntry>();

        foreach (var part in state.Parts)
        {
            if (Array.IndexOf(DollSlots, part.Slot) >= 0 && !bySlot.ContainsKey(part.Slot))
                bySlot[part.Slot] = part;
            else
                extras.Add(part);
        }

        // Row 1: head, centred over the body.
        DollGrid.AddChild(Spacer());
        DollGrid.AddChild(SlotCell(bySlot, "head"));
        DollGrid.AddChild(Spacer());

        // Row 2: gauntlets, then the core, then the chestplate. The core sits dead
        // centre because everything else on the readout hangs off it.
        DollGrid.AddChild(SlotCell(bySlot, "gloves"));
        DollGrid.AddChild(HardwareTile(state));
        DollGrid.AddChild(SlotCell(bySlot, "outerClothing"));

        // Row 3: legs.
        DollGrid.AddChild(Spacer());
        DollGrid.AddChild(SlotCell(bySlot, "shoes"));
        DollGrid.AddChild(Spacer());

        // Anything the doll has no anatomy for still has to be reachable.
        foreach (var part in extras)
        {
            var wrap = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 4, 0, 0),
            };

            wrap.AddChild(PartTile(part));
            ExtraPartsContainer.AddChild(wrap);
        }
    }

    private Control SlotCell(Dictionary<string, ChassisPartUiEntry> parts, string slot)
    {
        return parts.TryGetValue(slot, out var part) ? PartTile(part) : EmptyTile(slot);
    }

    private static Control Spacer() => new Control { MinSize = new Vector2(80, 4) };

    /// <summary>
    ///     One piece of the shell. The tile is the whole control: its frame carries the
    ///     state colour, so the doll reads as a diagram before you look at any text.
    /// </summary>
    private Control PartTile(ChassisPartUiEntry part)
    {
        var color = PartColor(part);

        var button = new ChassisButton
        {
            Accent = color,
            Selected = _selectedPart == part.Part && !_hardwareSelected,
            MinSize = new Vector2(80, 88),
            ToolTip = part.Name,
            Padding = 4f,
        };

        var stack = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalAlignment = HAlignment.Center,
        };

        stack.AddChild(new SpriteView(part.Part, _entMan)
        {
            SetSize = new Vector2(40, 40),
            OverrideDirection = Direction.South,
            HorizontalAlignment = HAlignment.Center,
        });

        stack.AddChild(new Label
        {
            Text = Loc.GetString(SlotLocId(part.Slot)),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = ChassisStyle.Text,
            HorizontalAlignment = HAlignment.Center,
        });

        stack.AddChild(IntegrityStrip(part));
        stack.AddChild(StateStrip(color));

        button.AddChild(stack);

        var id = part.Part;
        button.OnPressed += _ =>
        {
            _selectedPart = id;
            _hardwareSelected = false;
            Rebuild();
        };

        return button;
    }

    /// <summary>
    ///     A slot this chassis simply has no piece for.
    /// </summary>

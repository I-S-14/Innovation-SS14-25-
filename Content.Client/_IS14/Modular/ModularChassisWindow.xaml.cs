    /// </summary>
    private static Color PartColor(ChassisPartUiEntry part) => part.Ruptured
        ? ChassisStyle.Bad
        : part.Broken
            ? ChassisStyle.Warn
            : part.Sealed
                ? ChassisStyle.Good
                : part.Deployed
                    ? ChassisStyle.Accent
                    : ChassisStyle.Muted;


    private void UpdateModules(ModularChassisUiState state)
    {
        ModulesContainer.RemoveAllChildren();

        ModulesCountLabel.Text = Loc.GetString("chassis-ui-module-count", ("count", state.Modules.Count));

        if (state.Modules.Count == 0)
        {
            ModulesContainer.AddChild(new Label

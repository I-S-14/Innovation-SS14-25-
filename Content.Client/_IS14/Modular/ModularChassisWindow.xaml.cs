    private static Control StateStrip(Color color) => new PanelContainer
    {
        PanelOverride = new StyleBoxFlat(color),
        MinSize = new Vector2(48, 3),
        Margin = new Thickness(0, 3, 0, 0),
        HorizontalAlignment = HAlignment.Center,
    };

    /// <summary>
    ///     Condition under the tile, so the doll shows wear without being opened.
    /// </summary>
    private static Control IntegrityStrip(ChassisPartUiEntry part) => new IntegrityBar
    {
        Fraction = Fraction(part),
        Threshold = Threshold(part),
        SetSize = new Vector2(48, 4),
        Margin = new Thickness(0, 3, 0, 0),
        HorizontalAlignment = HAlignment.Center,
    };

    /// <summary>
    ///     Battered plating reads red whatever else it is doing: a sealed piece that has
    ///     stopped carrying its modules is the state a player most needs to notice.
    /// </summary>
    private static Color PartColor(ChassisPartUiEntry part) => part.Broken
        ? ChassisStyle.Bad
        : part.Sealed
            ? ChassisStyle.Good
            : part.Deployed
                ? ChassisStyle.Accent
                : ChassisStyle.Muted;

    private static float Fraction(ChassisPartUiEntry part) =>
        part.MaxIntegrity > 0f ? Math.Clamp(part.Integrity / part.MaxIntegrity, 0f, 1f) : 1f;

    private static float Threshold(ChassisPartUiEntry part) => part.BreakThreshold;


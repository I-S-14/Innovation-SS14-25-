    {
        var color = state.CoreName == null
            ? ChassisStyle.Bad
            : state.PanelOpen || state.InterfaceBroken
                ? ChassisStyle.Warn
                : ChassisStyle.Accent;

        var button = new ChassisButton
        {
            Accent = color,
            Selected = _hardwareSelected,
            MinSize = new Vector2(80, 88),
            ToolTip = Loc.GetString("chassis-ui-hardware"),
            Padding = 4f,
        };

        var stack = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalAlignment = HAlignment.Center,
        };

        stack.AddChild(new TextureRect
        {
            Texture = Icon("/Textures/_IS14/Objects/Modsuit/construction.rsi", "core-standard"),
            Stretch = TextureRect.StretchMode.KeepCentered,
            MinSize = new Vector2(40, 40),
        });

        stack.AddChild(new Label
        {
            Text = Loc.GetString("chassis-ui-hardware"),

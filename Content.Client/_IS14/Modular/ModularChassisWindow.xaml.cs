            ModulesContainer.AddChild(BuildModuleCard(module, state));
        }
    }

    private Control BuildModuleCard(ChassisModuleUiEntry module, ModularChassisUiState state)
    {
        var selected = state.SelectedModule == module.Module;
        var live = module.Active || selected;
        var kindColor = KindColor(module.Kind);

        var card = new PanelContainer
        {
            PanelOverride = ChassisStyle.Box(
                live ? ChassisStyle.PanelRaised : ChassisStyle.Backdrop,
                live ? kindColor.WithAlpha(0.7f) : ChassisStyle.Border),
            Margin = new Thickness(0, 0, 0, 4),
        };

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };

        // Colour rail down the left edge: kind at a glance, no reading required.
        row.AddChild(new PanelContainer
        {
            PanelOverride = new StyleBoxFlat(live ? kindColor : kindColor.WithAlpha(0.4f)),
            MinWidth = 3,
        });

        // The card body is a column, not a row. A horizontal box measures each child with
        // whatever the previous ones left over, so prose sharing a row with the buttons
        // would be handed their width too and run straight underneath them. Below the row
        // it gets the card's full width and wraps against a number that is actually true.
        var body = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(6, 5),
        };

        var top = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };

        top.AddChild(BuildModuleIcon(module, state));

        var expanded = _expandedModule == module.Module;

        var text = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };

        var header = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };

        header.AddChild(new Label
        {
            Text = module.Name,
            HorizontalExpand = true,
            ClipText = true,
            FontColorOverride = ChassisStyle.Text,
        });

        text.AddChild(header);

        text.AddChild(BuildStatPills(module, kindColor));

        // Say why the switch is dead rather than leaving the player to guess.
        if (module.Kind != ModuleKind.Passive && module.BlockReason != ModuleBlockReason.None)
        {
            text.AddChild(new Label
            {
                Text = Loc.GetString(BlockLocId(module.BlockReason)),
                StyleClasses = { "LabelSubText" },
                FontColorOverride = ChassisStyle.Warn,
            });
        }

        if (module.Cooldown > 0f && module.CooldownMax > 0f)
        {
            text.AddChild(new ProgressBar
            {
                MinValue = 0f,
                MaxValue = 1f,
                Value = Math.Clamp(1f - module.Cooldown / module.CooldownMax, 0f, 1f),
                MinHeight = 5,
                Margin = new Thickness(0, 3, 0, 0),
            });
        }

        // The whole text block is the expander. Making the card itself the button would
        // swallow clicks meant for the switch sitting inside it.
        var expander = new ChassisButton
        {
            Accent = kindColor,
            Selected = expanded,
            HorizontalExpand = true,
            Padding = 3f,
            ToolTip = Loc.GetString("chassis-ui-module-details"),
        };

        expander.AddChild(text);

        var id = module.Module;
        expander.OnPressed += _ =>
        {
            _expandedModule = expanded ? null : id;
            Rebuild();
        };

        top.AddChild(expander);
        top.AddChild(BuildModuleControls(module, state, selected, live, kindColor));
        body.AddChild(top);

        // Descriptions have to earn their room. A bay of eight modules each explaining
        // itself in three lines is a wall of text nobody reads, so the card keeps its
        // name and its numbers and hands over the prose only when asked.
        if (expanded)
        {
            var prose = new RichTextLabel
            {
                HorizontalExpand = true,
                Margin = new Thickness(0, 4, 0, 0),
                StyleClasses = { "LabelSubText" },
                Modulate = ChassisStyle.Muted,
            };

            prose.SetMessage(module.Description);
            body.AddChild(prose);

            foreach (var entry in module.Config)
            {
                if (BuildConfigControl(module.Module, entry) is { } control)
                    body.AddChild(control);
            }
        }

        row.AddChild(body);
        card.AddChild(row);
        return card;
    }

    /// <summary>
    ///     The module's own icon, with the pieces of the shell it is bolted to stacked
    ///     underneath it. There is dead space below a 32-pixel icon, and "which part does
    ///     this hang off?" is the question a dead module most often raises — so the answer
    ///     lives there, carrying the same state colour the paper doll uses.
    /// </summary>
    private Control BuildModuleIcon(ChassisModuleUiEntry module, ModularChassisUiState state)
    {
        var column = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            VerticalAlignment = VAlignment.Top,
            HorizontalAlignment = HAlignment.Center,
            Margin = new Thickness(0, 0, 6, 0),
        };

        var iconChip = new PanelContainer
        {
            PanelOverride = ChassisStyle.Box(ChassisStyle.Panel, ChassisStyle.Border, 1f, 2f),
        };

        iconChip.AddChild(new SpriteView(module.Module, _entMan)
        {
            SetSize = new Vector2(32, 32),
            OverrideDirection = Direction.South,
        });

        column.AddChild(iconChip);

        var links = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalAlignment = HAlignment.Center,
            Margin = new Thickness(0, 2, 0, 0),
        };

        foreach (var required in module.RequiredSlots)
        {
            foreach (var part in state.Parts)
            {
                if ((part.SlotFlag & required) == SlotFlags.NONE)
                    continue;

                links.AddChild(PartBadge(part));
            }
        }

        if (links.ChildCount > 0)
            column.AddChild(links);

        return column;
    }


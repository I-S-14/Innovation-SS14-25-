    private void UpdatePower(ModularChassisUiState state)
    {
        var present = state.MaxCharge > 0f;
        var fraction = present ? Math.Clamp(state.Charge / state.MaxCharge, 0f, 1f) : 0f;

        Battery.Present = present;
        Battery.Fraction = fraction;
        Battery.Draining = present && state.Draw > 0f && fraction <= 0.4f;

        if (present)
        {
            ChargePercentLabel.Text = $"{(int) MathF.Round(fraction * 100f)}%";
            ChargePercentLabel.FontColorOverride = fraction switch
            {
                <= 0.15f => ChassisStyle.Bad,
                <= 0.4f => ChassisStyle.Warn,
                _ => ChassisStyle.Good,
            };

            ChargeLabel.Text = Loc.GetString(
                "chassis-ui-charge-value",
                ("current", (int) MathF.Round(state.Charge)),
                ("max", (int) MathF.Round(state.MaxCharge)),
                ("draw", Num(state.Draw)));
        }
        else
        {
            ChargePercentLabel.Text = "—";
            ChargePercentLabel.FontColorOverride = ChassisStyle.Bad;
            ChargeLabel.Text = NoChargeReason(state);
        }

        CoreLabel.Text = state.CoreName ?? Loc.GetString("chassis-ui-no-core");
        CoreLabel.FontColorOverride = state.CoreName == null ? ChassisStyle.Bad : ChassisStyle.Muted;

        UpdateCore(state);
        UpdateTank(state);

        Complexity.Used = state.UsedComplexity;
        Complexity.Max = state.MaxComplexity;
        ComplexityLabel.Text = $"{state.UsedComplexity} / {state.MaxComplexity}";
        ComplexityLabel.FontColorOverride = state.UsedComplexity >= state.MaxComplexity
            ? ChassisStyle.Warn
            : ChassisStyle.Muted;
    }

    /// <summary>
    ///     The two things a core can offer the panel. Both hide themselves when the
    ///     installed core has nothing of the sort — an empty row of dead buttons reads as
    ///     broken, not as "not applicable".
    /// </summary>
    /// <summary>
    ///     Why there is nothing to draw on. An empty socket and a core with its cell
    ///     pulled read identically from the battery's side and need different things done
    ///     about them, so they are not allowed to share a message.
    /// </summary>
    private static string NoChargeReason(ModularChassisUiState state)
    {
        return Loc.GetString(state.CoreName == null
            ? "chassis-ui-no-core"
            : "chassis-ui-no-cell");
    }

    private void UpdateCore(ModularChassisUiState state)
    {
        // A core that takes a cell shows exactly one of the two buttons: whichever
        // direction the slot can currently go.
        var hasCell = state.CoreCellName != null;

        _cellButton.Visible = state.CoreTakesCell && hasCell;
        _cellButton.Disabled = !state.PanelOpen;
        _cellButton.ToolTip = Loc.GetString(state.PanelOpen
            ? "chassis-ui-eject-cell-tooltip"
            : "chassis-ui-eject-needs-panel");

        if (_cellButton.Visible)
        {
            _cellButton.SetContent(
                UiIcon(state.PanelOpen ? IconEject : IconNo),
                Loc.GetString("chassis-ui-eject-cell"));
        }

        _insertCellButton.Visible = state.CoreTakesCell && !hasCell;
        _insertCellButton.Disabled = !state.PanelOpen;
        _insertCellButton.ToolTip = Loc.GetString(state.PanelOpen
            ? "chassis-ui-insert-cell-tooltip"
            : "chassis-ui-eject-needs-panel");

        if (_insertCellButton.Visible)
        {
            _insertCellButton.SetContent(
                UiIcon(state.PanelOpen ? IconPutAway : IconNo),
                Loc.GetString("chassis-ui-insert-cell"));
        }

        _hopperButton.Visible = state.CoreHasHopper;
        _hopperButton.ToolTip = Loc.GetString("chassis-ui-hopper-tooltip");
    }

    /// <summary>
    ///     The bottle. Nothing to show without an atmospheric module, so the dial reads
    ///     dead rather than pretending the suit has an empty tank.
    /// </summary>
    private void UpdateTank(ModularChassisUiState state)
    {
        Tank.Present = state.TankPresent;
        Tank.Pumping = state.TankPumping;

        var target = state.TankTargetPressure > 0f ? state.TankTargetPressure : 1f;
        Tank.Fraction = state.TankPresent ? Math.Clamp(state.TankPressure / target, 0f, 1f) : 0f;

        TankGasContainer.RemoveAllChildren();
        TankSealRow.RemoveAllChildren();

        _pumpButton.Visible = state.TankPresent;
        _valveButton.Visible = state.TankPresent;
        _internalsButton.Visible = state.TankPresent;

        if (!state.TankPresent)
        {
            TankPressureLabel.Text = Loc.GetString("chassis-ui-no-tank");
            TankPressureLabel.FontColorOverride = ChassisStyle.Muted;
            TankTemperatureLabel.Text = string.Empty;
            TankContentsLabel.Text = string.Empty;
            return;
        }

        TankPressureLabel.Text = Loc.GetString("chassis-ui-tank-value", ("kpa", (int) MathF.Round(state.TankPressure)));
        TankPressureLabel.FontColorOverride = Tank.NeedleColor;

        // Celsius, because nobody sizing up a bottle thinks in kelvin. An empty bottle
        // has a temperature on paper and nothing to have it, so it does not get a reading.
        TankTemperatureLabel.Text = state.TankEmpty
            ? string.Empty
            : Loc.GetString(
                "chassis-ui-tank-temperature",
                ("celsius", (int) MathF.Round(state.TankTemperature - 273.15f)));

        TankTemperatureLabel.FontColorOverride = ChassisStyle.Muted;

        UpdateTankGases(state);

        // Whether the suit is holding pressure at all, as a tick or a cross. It is the
        // precondition for both the compressor and internals, so it gets its own line
        // rather than being explained again inside every message that depends on it.
        var sealColor = state.TankCanPump ? ChassisStyle.Good : ChassisStyle.Bad;

        TankSealRow.AddChild(ChassisStyle.Icon(
            UiIcon(state.TankCanPump ? IconCheck : IconCross),
            14f,
            sealColor));

        TankSealRow.AddChild(new Label
        {
            Text = Loc.GetString("chassis-ui-tank-seal"),
            Margin = new Thickness(4, 0, 0, 0),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = sealColor,
        });

        TankSealRow.ToolTip = Loc.GetString("chassis-ui-tank-unsealed");

        TankContentsLabel.Text = string.IsNullOrEmpty(state.TankContents)
            ? Loc.GetString("chassis-ui-tank-idle")
            : state.TankContents;

        TankContentsLabel.FontColorOverride = state.TankPumping ? ChassisStyle.Accent : ChassisStyle.Muted;

        _pumpButton.Selected = state.TankPumping;
        _pumpButton.Disabled = !state.TankCanPump;
        _pumpButton.Accent = state.TankCanPump ? ChassisStyle.Accent : ChassisStyle.Muted;
        _pumpButton.ToolTip = Loc.GetString(state.TankCanPump
            ? "chassis-ui-tank-pump-tooltip"
            : "chassis-ui-tank-unsealed");

        _valveButton.Selected = state.TankValveOpen;
        _valveButton.SetContent(
            UiIcon(state.TankValveOpen ? IconRetract : IconDeploy),
            Loc.GetString(state.TankValveOpen ? "chassis-ui-tank-valve-close" : "chassis-ui-tank-valve"));

        _valveButton.ToolTip = Loc.GetString("chassis-ui-tank-valve-tooltip");

        // Breathing asks for more than the compressor does: every piece closed, and a
        // valve that is not busy emptying the bottle into the room.
        var canBreathe = state.TankCanBreathe && !state.TankValveOpen;

        _internalsButton.Selected = state.TankInternalsOn;
        _internalsButton.Disabled = !canBreathe && !state.TankInternalsOn;
        _internalsButton.Accent = canBreathe || state.TankInternalsOn ? ChassisStyle.Good : ChassisStyle.Muted;

        _internalsButton.SetContent(
            UiIcon(IconInternals),
            Loc.GetString(state.TankInternalsOn
                ? "chassis-ui-tank-internals-off"
                : "chassis-ui-tank-internals"));

        _internalsButton.ToolTip = Loc.GetString(canBreathe || state.TankInternalsOn
            ? "chassis-ui-tank-internals-tooltip"
            : "chassis-ui-tank-internals-needs-seal");
    }

    /// <summary>
    ///     What is actually in the bottle. Only the three largest shares are listed: a
    ///     readout that spells out four decimal places of trace argon is a readout nobody
    ///     glances at.
    /// </summary>
    private void UpdateTankGases(ModularChassisUiState state)
    {
        if (state.TankGases.Count == 0)
        {
            TankGasContainer.AddChild(new Label
            {
                Text = Loc.GetString("chassis-ui-tank-empty"),
                StyleClasses = { "LabelSubText" },
                FontColorOverride = ChassisStyle.Muted,
            });

            return;
        }

        var shown = 0;
        var rest = 0f;

        foreach (var entry in state.TankGases)
        {
            if (shown >= 3 || entry.Fraction < 0.005f)
            {
                rest += entry.Fraction;
                continue;
            }

            shown++;

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
            };

            row.AddChild(new Label
            {
                Text = GasName(entry.Gas),
                StyleClasses = { "LabelSubText" },
                FontColorOverride = GasColor(entry.Gas),
                HorizontalExpand = true,
                ClipText = true,
            });

            row.AddChild(new Label
            {
                Text = Loc.GetString("chassis-ui-tank-share", ("percent", (int) MathF.Round(entry.Fraction * 100f))),
                StyleClasses = { "LabelSubText" },
                FontColorOverride = ChassisStyle.Muted,
            });

            TankGasContainer.AddChild(row);
        }

        if (rest < 0.005f)
            return;

        TankGasContainer.AddChild(new Label
        {
            Text = Loc.GetString("chassis-ui-tank-rest", ("percent", (int) MathF.Round(rest * 100f))),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = ChassisStyle.Muted,
        });
    }

    private string GasName(Gas gas)
    {
        return _protos.TryIndex<GasPrototype>(gas.ToString(), out var proto)
            ? Loc.GetString(proto.Name)
            : gas.ToString();
    }

    private Color GasColor(Gas gas)
    {
        if (!_protos.TryIndex<GasPrototype>(gas.ToString(), out var proto)
            || string.IsNullOrEmpty(proto.Color)
            || Color.TryFromHex("#" + proto.Color) is not { } color)
        {
            return ChassisStyle.Text;
        }

        // Gas colours are picked to show up against a dark tile, not against panel grey.
        return Color.InterpolateBetween(color, ChassisStyle.Text, 0.35f);
    }


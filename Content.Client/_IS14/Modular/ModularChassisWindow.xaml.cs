    /// <summary>
    ///     The switch and the eject button, stacked at the right of a module card.
    ///     Pulling a module lives here rather than in the context menu: it belongs with
    ///     the rest of the hardware, and it needs the panel open to say so.
    /// </summary>
    private Control BuildModuleControls(
        ChassisModuleUiEntry module,
        ModularChassisUiState state,
        bool selected,
        bool live,
        Color kindColor)
    {
        var column = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            VerticalAlignment = VAlignment.Center,
            Margin = new Thickness(6, 0, 0, 0),
        };

        // Passive modules have nothing to switch.
        if (module.Kind != ModuleKind.Passive)
        {
            var blocked = module.BlockReason != ModuleBlockReason.None;

            var button = ChassisButton.Make(
                UiIcon(blocked ? IconNo : ActionIcon(module, selected)),
                ActionText(module, selected),
                live ? ChassisStyle.Good : kindColor);

            button.Selected = live;
            button.MinWidth = 116;
            button.Disabled = blocked;

            var moduleId = module.Module;
            button.OnPressed += _ => OnSelectModule?.Invoke(moduleId);
            column.AddChild(button);
        }

        if (!module.Removable)
            return column;

        var canEject = state.PanelOpen;

        var eject = ChassisButton.Make(
            UiIcon(canEject ? IconEject : IconNo),
            Loc.GetString("chassis-ui-eject"),
            canEject ? ChassisStyle.Warn : ChassisStyle.Muted,
            iconSize: 16f,
            padding: 4f);

        eject.MinWidth = 116;
        eject.Disabled = !canEject;
        eject.ToolTip = Loc.GetString(canEject ? "chassis-ui-eject-tooltip" : "chassis-ui-eject-needs-panel");

        if (module.Kind != ModuleKind.Passive)
            eject.Margin = new Thickness(0, 4, 0, 0);

        var id = module.Module;
        eject.OnPressed += _ => OnEjectModule?.Invoke(id);
        column.AddChild(eject);

        return column;
    }

    /// <summary>
    ///     One of a module's settings. Rendered from the generic description the module
    ///     sends, so a new configurable module needs no window code at all.
    /// </summary>
    private Control? BuildConfigControl(NetEntity module, ModuleConfigEntry entry)
    {
        switch (entry.Kind)
        {
            case ModuleConfigKind.Bool:
            {
                var on = entry.Value is true;

                var button = ChassisButton.Make(
                    UiIcon(on ? IconCheck : IconCross),
                    entry.Label,
                    on ? ChassisStyle.Good : ChassisStyle.Muted,
                    iconSize: 14f,
                    padding: 3f);

                button.Selected = on;
                button.HorizontalExpand = true;
                button.Margin = new Thickness(0, 2, 0, 0);
                button.OnPressed += _ => OnConfigureModule?.Invoke(module, entry.Key, !on);

                return button;
            }

            case ModuleConfigKind.Button:
            {
                var button = ChassisButton.Make(UiIcon(IconZap), entry.Label, ChassisStyle.Accent,
                    iconSize: 14f, padding: 3f);

                button.HorizontalExpand = true;
                button.Margin = new Thickness(0, 2, 0, 0);
                button.OnPressed += _ => OnConfigureModule?.Invoke(module, entry.Key, null);

                return button;
            }

            case ModuleConfigKind.Choice when entry.Choices is { Length: > 0 }:
            {
                var row = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    HorizontalExpand = true,
                    Margin = new Thickness(0, 2, 0, 0),
                };

                foreach (var choice in entry.Choices)
                {
                    var picked = entry.Value as string == choice;

                    var button = ChassisButton.Make(null, choice,
                        picked ? ChassisStyle.Good : ChassisStyle.Muted, padding: 3f);

                    button.Selected = picked;
                    button.Margin = new Thickness(0, 0, 3, 0);
                    button.OnPressed += _ => OnConfigureModule?.Invoke(module, entry.Key, choice);

                    row.AddChild(button);
                }

                return row;
            }

            default:
                return null;
        }
    }

    private Control BuildStatPills(ChassisModuleUiEntry module, Color kindColor)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(0, 3, 0, 0),
        };

        row.AddChild(ChassisStyle.IconChip(
            UiIcon(IconComplexity),
            module.Complexity.ToString(CultureInfo.InvariantCulture),
            ChassisStyle.Muted,
            Loc.GetString("chassis-ui-complexity")));

        if (module.IdleDraw > 0f)
        {
            row.AddChild(ChassisStyle.IconChip(
                UiIcon(IconBolt),
                Loc.GetString("chassis-ui-module-idle", ("value", Num(module.IdleDraw))),
                ChassisStyle.Muted,
                Loc.GetString("chassis-ui-module-idle-tooltip")));
        }

        if (module.ActiveDraw > 0f)
        {
            row.AddChild(ChassisStyle.IconChip(
                UiIcon(IconBolt),
                Loc.GetString("chassis-ui-module-active", ("value", Num(module.ActiveDraw))),
                ChassisStyle.Warn,
                Loc.GetString("chassis-ui-module-active-tooltip")));
        }

        if (module.UseCost > 0f)
        {
            row.AddChild(ChassisStyle.IconChip(
                UiIcon(IconBolt),
                Loc.GetString("chassis-ui-module-use", ("value", Num(module.UseCost))),
                ChassisStyle.Warn,
                Loc.GetString("chassis-ui-module-use-tooltip")));
        }

        // What kind of module this is sits at the far end of the numbers rather than
        // beside the name: the name is what you look for, the kind is what you confirm.
        row.AddChild(new Control { HorizontalExpand = true });
        row.AddChild(ChassisStyle.Chip(Loc.GetString(KindLocId(module.Kind)), kindColor));

        return row;
    }

    #endregion

    #region Header actions

    private void UpdateActions(ModularChassisUiState state)
    {
        _deployButton.SetContent(
            UiIcon(state.Active ? IconNo : state.AnyDeployed ? IconRetract : IconDeploy),
            Loc.GetString(state.AnyDeployed ? "chassis-ui-retract-all" : "chassis-ui-deploy-all"));

        _deployButton.Disabled = state.Active;
        _deployButton.Accent = state.AnyDeployed ? ChassisStyle.Warn : ChassisStyle.Accent;

        _sealButton.SetContent(
            UiIcon(!state.AnyDeployed ? IconNo : state.Active ? IconUnseal : IconSeal),
            Loc.GetString(state.Active ? "chassis-ui-deactivate" : "chassis-ui-activate"));

        _sealButton.Disabled = !state.AnyDeployed;
        _sealButton.Selected = state.Active;
    }

    #endregion

    #region Helpers

    /// <summary>
    ///     Redraws from the last known state — used when a click only changed what the
    ///     window is showing, not what the suit is doing.
    /// </summary>
    private void Rebuild()
    {
        if (_state != null)
            UpdateState(_state);
    }

    private Texture Icon(string rsi, string state)
    {
        return _sprites.Frame0(new SpriteSpecifier.Rsi(new ResPath(rsi), state));
    }

    /// <summary>
    ///     Interface icons, cached: the window rebuilds itself on every state push and
    ///     resolving the same handful of textures each time would be waste.
    /// </summary>
    private Texture UiIcon(string path)
    {
        if (_icons.TryGetValue(path, out var cached))
            return cached;

        return _icons[path] = _sprites.Frame0(new SpriteSpecifier.Texture(new ResPath(path)));
    }

    /// <summary>
    ///     Fluent prints a bare float at full binary precision — 0.15f becomes
    ///     0.150000000596046448 — so numbers reach it already formatted.
    /// </summary>
    private static string Num(float value) =>
        value.ToString("0.##", CultureInfo.InvariantCulture);

    private static string SlotLocId(string slot) => slot switch
    {
        "head" => "chassis-ui-slot-head",
        "outerClothing" => "chassis-ui-slot-chest",
        "gloves" => "chassis-ui-slot-hands",
        "shoes" => "chassis-ui-slot-feet",
        _ => "chassis-ui-slot-other",
    };

    private static string ActionText(ChassisModuleUiEntry module, bool selected)
    {
        if (module.ActionText != null)
            return Loc.GetString(module.ActionText);

        return module.Kind switch
        {
            ModuleKind.Usable => Loc.GetString("chassis-ui-module-use-button"),
            ModuleKind.Active => Loc.GetString(selected
                ? "chassis-ui-module-deselect"
                : "chassis-ui-module-select"),
            _ => Loc.GetString(module.Active
                ? "chassis-ui-module-off"
                : "chassis-ui-module-on"),
        };
    }

    private static string ActionIcon(ChassisModuleUiEntry module, bool selected)
    {
        if (module.ActionIcon != null)
            return module.ActionIcon;

        return module.Kind switch
        {
            ModuleKind.Usable => IconZap,
            ModuleKind.Active => selected ? IconPutAway : IconTakeOut,
            _ => IconPower,
        };
    }

    private static string KindLocId(ModuleKind kind) => kind switch
    {
        ModuleKind.Passive => "chassis-ui-kind-passive",
        ModuleKind.Toggleable => "chassis-ui-kind-toggleable",
        ModuleKind.Usable => "chassis-ui-kind-usable",
        ModuleKind.Active => "chassis-ui-kind-active",
        _ => "chassis-ui-kind-passive",
    };

    private static Color KindColor(ModuleKind kind) => kind switch
    {
        ModuleKind.Toggleable => ChassisStyle.Accent,
        ModuleKind.Usable => ChassisStyle.Warn,
        ModuleKind.Active => Color.FromHex("#E5883F"),
        _ => ChassisStyle.Muted,
    };

    private static string BlockLocId(ModuleBlockReason reason) => reason switch
    {
        ModuleBlockReason.NoPower => "chassis-module-no-power",
        ModuleBlockReason.Cooldown => "chassis-module-cooldown",
        ModuleBlockReason.MissingParts => "chassis-module-missing-parts",
        ModuleBlockReason.ChassisInactive => "chassis-module-chassis-inactive",
        ModuleBlockReason.NotWorn => "chassis-module-not-worn",
        ModuleBlockReason.Incapacitated => "chassis-module-incapacitated",
        ModuleBlockReason.Malfunctioning => "chassis-module-malfunctioning",
        _ => "chassis-module-unavailable",
    };

    #endregion

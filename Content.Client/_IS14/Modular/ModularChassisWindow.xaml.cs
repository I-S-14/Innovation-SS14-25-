    #region Modules

    private void UpdateModules(ModularChassisUiState state)
    {
        ModulesContainer.RemoveAllChildren();

        ModulesCountLabel.Text = Loc.GetString("chassis-ui-module-count", ("count", state.Modules.Count));

        if (state.Modules.Count == 0)
        {
            ModulesContainer.AddChild(new Label
            {
                Text = Loc.GetString("chassis-ui-no-modules"),
                StyleClasses = { "LabelSubText" },
                FontColorOverride = ChassisStyle.Muted,
                Margin = new Thickness(4),
            });

            return;
        }

        foreach (var module in state.Modules)
        {
            ModulesContainer.AddChild(BuildModuleCard(module, state));
        }
    }

    private Control BuildModuleCard(ChassisModuleUiEntry module, ModularChassisUiState state)
    {
        var selected = state.SelectedModule == module.Module;
        var live = module.Active || selected;
        var kindColor = KindColor(module.Kind);

        var card = new PanelContainer
        {
            PanelOverride = ChassisStyle.Box(
                live ? ChassisStyle.PanelRaised : ChassisStyle.Backdrop,
                live ? kindColor.WithAlpha(0.7f) : ChassisStyle.Border),
            Margin = new Thickness(0, 0, 0, 4),
        };

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };

        // Colour rail down the left edge: kind at a glance, no reading required.
        row.AddChild(new PanelContainer
        {
            PanelOverride = new StyleBoxFlat(live ? kindColor : kindColor.WithAlpha(0.4f)),
            MinWidth = 3,
        });

        var body = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(6, 5),
        };

        body.AddChild(BuildModuleIcon(module, state));

        var text = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };

        var header = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };

        header.AddChild(new Label
        {
            Text = module.Name,
            HorizontalExpand = true,
            ClipText = true,
            FontColorOverride = ChassisStyle.Text,
        });

        header.AddChild(ChassisStyle.Chip(Loc.GetString(KindLocId(module.Kind)), kindColor));
        text.AddChild(header);

        text.AddChild(new Label
        {
            Text = module.Description,
            StyleClasses = { "LabelSubText" },
            FontColorOverride = ChassisStyle.Muted,
        });

        text.AddChild(BuildStatPills(module));

        // Say why the switch is dead rather than leaving the player to guess.
        if (module.Kind != ModuleKind.Passive && module.BlockReason != ModuleBlockReason.None)
        {
            text.AddChild(new Label
            {
                Text = Loc.GetString(BlockLocId(module.BlockReason)),
                StyleClasses = { "LabelSubText" },
                FontColorOverride = ChassisStyle.Warn,
            });
        }

        if (module.Cooldown > 0f && module.CooldownMax > 0f)
        {
            text.AddChild(new ProgressBar
            {
                MinValue = 0f,
                MaxValue = 1f,
                Value = Math.Clamp(1f - module.Cooldown / module.CooldownMax, 0f, 1f),
                MinHeight = 5,
                Margin = new Thickness(0, 3, 0, 0),
            });
        }

        body.AddChild(text);
        body.AddChild(BuildModuleControls(module, state, selected, live, kindColor));

        row.AddChild(body);
        card.AddChild(row);
        return card;
    }

    /// <summary>
    ///     The module's own icon, with the pieces of the shell it is bolted to stacked
    ///     underneath it. There is dead space below a 32-pixel icon, and "which part does
    ///     this hang off?" is the question a dead module most often raises — so the answer
    ///     lives there, carrying the same state colour the paper doll uses.
    /// </summary>
    private Control BuildModuleIcon(ChassisModuleUiEntry module, ModularChassisUiState state)
    {
        var column = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            VerticalAlignment = VAlignment.Top,
            HorizontalAlignment = HAlignment.Center,
            Margin = new Thickness(0, 0, 6, 0),
        };

        var iconChip = new PanelContainer
        {
            PanelOverride = ChassisStyle.Box(ChassisStyle.Panel, ChassisStyle.Border, 1f, 2f),
        };

        iconChip.AddChild(new SpriteView(module.Module, _entMan)
        {
            SetSize = new Vector2(32, 32),
            OverrideDirection = Direction.South,
        });

        column.AddChild(iconChip);

        var links = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalAlignment = HAlignment.Center,
            Margin = new Thickness(0, 2, 0, 0),
        };

        foreach (var required in module.RequiredSlots)
        {
            foreach (var part in state.Parts)
            {
                if ((part.SlotFlag & required) == SlotFlags.NONE)
                    continue;

                links.AddChild(PartBadge(part));
            }
        }

        if (links.ChildCount > 0)
            column.AddChild(links);

        return column;
    }

    /// <summary>
    ///     One shell piece as a thumbnail: the part's own sprite over a bar in its state
    ///     colour, so a module card shows at a glance that its gauntlet is stowed or beaten in.
    /// </summary>
    private Control PartBadge(ChassisPartUiEntry part)
    {
        var color = PartColor(part);

        var wrap = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(1, 0),
            ToolTip = $"{part.Name} — {Loc.GetString(PartStateLocId(part))}",
        };

        wrap.AddChild(new SpriteView(part.Part, _entMan)
        {
            SetSize = new Vector2(16, 16),
            OverrideDirection = Direction.South,
            HorizontalAlignment = HAlignment.Center,
        });

        wrap.AddChild(new PanelContainer
        {
            PanelOverride = new StyleBoxFlat(color),
            MinSize = new Vector2(16, 2),
            HorizontalAlignment = HAlignment.Center,
        });

        return wrap;
    }

    private static string PartStateLocId(ChassisPartUiEntry part) => part.Broken
        ? "chassis-ui-part-broken"
        : part.Sealed
            ? "chassis-ui-part-sealed"
            : part.Deployed
                ? "chassis-ui-part-deployed"
                : "chassis-ui-part-stowed";

    /// <summary>
    ///     The switch and the eject button, stacked at the right of a module card.
    ///     Pulling a module lives here rather than in the context menu: it belongs with
    ///     the rest of the hardware, and it needs the panel open to say so.
    /// </summary>
    private Control BuildModuleControls(
        ChassisModuleUiEntry module,
        ModularChassisUiState state,
        bool selected,
        bool live,
        Color kindColor)
    {
        var column = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            VerticalAlignment = VAlignment.Center,
            Margin = new Thickness(6, 0, 0, 0),
        };

        // Passive modules have nothing to switch.
        if (module.Kind != ModuleKind.Passive)
        {
            var blocked = module.BlockReason != ModuleBlockReason.None;

            var button = ChassisButton.Make(
                UiIcon(blocked ? IconNo : ActionIcon(module, selected)),
                ActionText(module, selected),
                live ? ChassisStyle.Good : kindColor);

            button.Selected = live;
            button.MinWidth = 116;
            button.Disabled = blocked;

            var moduleId = module.Module;
            button.OnPressed += _ => OnSelectModule?.Invoke(moduleId);
            column.AddChild(button);
        }

        if (!module.Removable)
            return column;

        var canEject = state.PanelOpen;

        var eject = ChassisButton.Make(
            UiIcon(canEject ? IconEject : IconNo),
            Loc.GetString("chassis-ui-eject"),
            canEject ? ChassisStyle.Warn : ChassisStyle.Muted,
            iconSize: 16f,
            padding: 4f);

        eject.MinWidth = 116;
        eject.Disabled = !canEject;
        eject.ToolTip = Loc.GetString(canEject ? "chassis-ui-eject-tooltip" : "chassis-ui-eject-needs-panel");

        if (module.Kind != ModuleKind.Passive)
            eject.Margin = new Thickness(0, 4, 0, 0);

        var id = module.Module;
        eject.OnPressed += _ => OnEjectModule?.Invoke(id);
        column.AddChild(eject);

        return column;
    }

    private static Control BuildStatPills(ChassisModuleUiEntry module)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Margin = new Thickness(0, 3, 0, 0),
        };

        row.AddChild(ChassisStyle.Chip(
            Loc.GetString("chassis-ui-module-complexity", ("value", module.Complexity)),
            ChassisStyle.Muted));

        if (module.IdleDraw > 0f)
        {
            row.AddChild(ChassisStyle.Chip(
                Loc.GetString("chassis-ui-module-idle", ("value", Num(module.IdleDraw))),
                ChassisStyle.Muted));
        }

        if (module.ActiveDraw > 0f)
        {
            row.AddChild(ChassisStyle.Chip(
                Loc.GetString("chassis-ui-module-active", ("value", Num(module.ActiveDraw))),
                ChassisStyle.Warn));
        }

        if (module.UseCost > 0f)
        {
            row.AddChild(ChassisStyle.Chip(
                Loc.GetString("chassis-ui-module-use", ("value", Num(module.UseCost))),
                ChassisStyle.Warn));
        }

        return row;
    }


    #region Helpers

    /// <summary>
    ///     Redraws from the last known state — used when a click only changed what the
    ///     window is showing, not what the suit is doing.
    /// </summary>
    private void Rebuild()
    {
        if (_state != null)
            UpdateState(_state);
    }

    private Texture Icon(string rsi, string state)
    {
        return _sprites.Frame0(new SpriteSpecifier.Rsi(new ResPath(rsi), state));
    }

    /// <summary>
    ///     Interface icons, cached: the window rebuilds itself on every state push and
    ///     resolving the same handful of textures each time would be waste.
    /// </summary>
    private Texture UiIcon(string path)
    {
        if (_icons.TryGetValue(path, out var cached))
            return cached;

        return _icons[path] = _sprites.Frame0(new SpriteSpecifier.Texture(new ResPath(path)));
    }

    /// <summary>
    ///     Fluent prints a bare float at full binary precision — 0.15f becomes
    ///     0.150000000596046448 — so numbers reach it already formatted.
    /// </summary>
    private static string Num(float value) =>
        value.ToString("0.##", CultureInfo.InvariantCulture);

    private static string SlotLocId(string slot) => slot switch
    {
        "head" => "chassis-ui-slot-head",
        "outerClothing" => "chassis-ui-slot-chest",
        "gloves" => "chassis-ui-slot-hands",
        "shoes" => "chassis-ui-slot-feet",
        _ => "chassis-ui-slot-other",
    };

    private static string ActionText(ChassisModuleUiEntry module, bool selected)
    {
        if (module.ActionText != null)
            return Loc.GetString(module.ActionText);

        return module.Kind switch
        {
            ModuleKind.Usable => Loc.GetString("chassis-ui-module-use-button"),
            ModuleKind.Active => Loc.GetString(selected
                ? "chassis-ui-module-deselect"
                : "chassis-ui-module-select"),
            _ => Loc.GetString(module.Active
                ? "chassis-ui-module-off"
                : "chassis-ui-module-on"),
        };
    }

    private static string ActionIcon(ChassisModuleUiEntry module, bool selected)
    {
        if (module.ActionIcon != null)
            return module.ActionIcon;

        return module.Kind switch
        {
            ModuleKind.Usable => IconZap,
            ModuleKind.Active => selected ? IconPutAway : IconTakeOut,
            _ => IconPower,
        };
    }

    private static string KindLocId(ModuleKind kind) => kind switch
    {
        ModuleKind.Passive => "chassis-ui-kind-passive",
        ModuleKind.Toggleable => "chassis-ui-kind-toggleable",
        ModuleKind.Usable => "chassis-ui-kind-usable",
        ModuleKind.Active => "chassis-ui-kind-active",
        _ => "chassis-ui-kind-passive",
    };

    private static Color KindColor(ModuleKind kind) => kind switch
    {
        ModuleKind.Toggleable => ChassisStyle.Accent,
        ModuleKind.Usable => ChassisStyle.Warn,
        ModuleKind.Active => Color.FromHex("#E5883F"),
        _ => ChassisStyle.Muted,
    };

    private static string BlockLocId(ModuleBlockReason reason) => reason switch
    {
        ModuleBlockReason.NoPower => "chassis-module-no-power",
        ModuleBlockReason.Cooldown => "chassis-module-cooldown",
        ModuleBlockReason.MissingParts => "chassis-module-missing-parts",
        ModuleBlockReason.ChassisInactive => "chassis-module-chassis-inactive",
        ModuleBlockReason.NotWorn => "chassis-module-not-worn",
        ModuleBlockReason.Incapacitated => "chassis-module-incapacitated",
        ModuleBlockReason.Malfunctioning => "chassis-module-malfunctioning",
        _ => "chassis-module-unavailable",
    };


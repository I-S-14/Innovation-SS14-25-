/// <summary>
///     The chassis readout. Deliberately knows nothing about MOD suits specifically —
///     it renders charge, complexity, shell parts and modules, so a mech can open the same
///     window once the mech rework lands.
///
///     The layout is a dashboard rather than a list: a paper doll for the shell on the left
///     with a menu that expands under whichever piece you press, the power plant and module
///     bay on the right, and the two controls a wearer actually reaches for along the bottom.
///     Every control the player can press is captioned with an icon, because this is a suit
///     panel and suit panels do not spell things out.
/// </summary>

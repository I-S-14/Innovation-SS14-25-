using Content.Shared._IS14.Medical.BloodType;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._IS14.Medical.BloodType;

/// <summary>
/// A labelled well on the card: the antibody above it, and whatever it did below.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class BloodTestWell : Control
{
    private BloodTestWellState _state;
    private BloodTestPalette _palette = BloodTestPalette.Screen;
    private bool _spellItOut = true;

    public BloodTestWell()
    {
        RobustXamlLoader.Load(this);
    }

    /// <summary>
    /// Which surface this well is printed on, and whether it is allowed to spell the answer
    /// out underneath. Set before <see cref="SetWell"/>.
    /// </summary>
    /// <remarks>
    /// The strip does not spell it out. Clumped or not clumped is a thing you can see, and
    /// printing a plus sign under it would be the card doing the reading for you — which is
    /// the one job the strip is not supposed to have.
    /// </remarks>
    public void SetPalette(BloodTestPalette palette, bool spellItOut = true)
    {
        _palette = palette;
        _spellItOut = spellItOut;

        Well.Palette = palette;
        TitleLabel.FontColorOverride = palette.Title;
        ResultLabel.Visible = spellItOut;
    }

    public void SetWell(BloodTestWellState state)
    {
        _state = state;

        TitleLabel.Text = Loc.GetString("is14-blood-test-well-title", ("antigen", state.ShortName));
        Well.Positive = state.Positive;

        SetProgress(0f, 0f);
    }

    /// <summary>
    /// Advances this well. The verdict is withheld until the reaction has actually finished,
    /// so nobody reads an answer off a well that is still working.
    /// </summary>
    public void SetProgress(float filled, float reaction)
    {
        Well.Filled = filled;
        Well.Reaction = reaction;

        if (!_spellItOut)
            return;

        if (reaction < 1f)
        {
            ResultLabel.Text = "…";
            ResultLabel.FontColorOverride = _palette.Pending;
            return;
        }

        ResultLabel.Text = Loc.GetString(_state.Positive
            ? "is14-blood-test-well-positive"
            : "is14-blood-test-well-negative");

        ResultLabel.FontColorOverride = _state.Positive ? _palette.Clump : _palette.Negative;
    }
}

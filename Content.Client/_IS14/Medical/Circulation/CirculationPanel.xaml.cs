using Content.Shared._IS14.Medical.Circulation;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._IS14.Medical.Circulation;

/// <summary>
/// The circulation block of the health analyser: a live trace and the saturation behind it.
/// </summary>
/// <remarks>
/// Reads straight off the patient's networked component rather than waiting to be handed a
/// message, so the trace keeps running between scans instead of freezing on the last snapshot.
/// That is the difference between a readout and a photograph of one.
/// </remarks>
[GenerateTypedNameReferences]
public sealed partial class CirculationPanel : BoxContainer
{
    [Dependency] private readonly IEntityManager _entities = default!;

    private EntityUid? _target;

    public CirculationPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

    }

    /// <summary>Points the panel at a patient, or hides it if they have no circulation.</summary>
    public void SetTarget(EntityUid? target)
    {
        _target = target;
        Visible = target != null && _entities.HasComponent<CirculationComponent>(target.Value);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!Visible
            || _target is not { } target
            || !_entities.TryGetComponent<CirculationComponent>(target, out var comp))
        {
            return;
        }

        Refresh(comp);
    }

    private void Refresh(CirculationComponent comp)
    {
        var (stageKey, stageColor) = comp.Stage switch
        {
            ShockStage.Compensating => ("is14-analyzer-stage-compensating", Amber),
            ShockStage.Decompensating => ("is14-analyzer-stage-decompensating", Orange),
            ShockStage.Shock => ("is14-analyzer-stage-shock", Red),
            _ => ("is14-analyzer-stage-normal", Green),
        };

        StageLabel.Text = Loc.GetString(stageKey);
        StageLabel.FontColorOverride = stageColor;

        // The trace takes the colour of the stage, so the strip itself is the alarm.
        Ecg.HeartRate = comp.HeartRate;
        Ecg.Beating = comp.HeartRate > 1f;
        Ecg.TraceColor = stageColor;

        RateLabel.Text = Ecg.Beating
            ? Loc.GetString("is14-analyzer-bpm", ("rate", (int) MathF.Round(comp.HeartRate)))
            : Loc.GetString("is14-analyzer-asystole");
        RateLabel.FontColorOverride = stageColor;

        DeliveryLabel.Text = Loc.GetString(
            "is14-analyzer-delivery",
            ("percent", (int) MathF.Round(comp.Delivery * 100f)));
        DeliveryLabel.FontColorOverride = comp.Delivery + 0.01f < comp.Demand ? Red : Muted;

        var saturation = Math.Clamp(comp.Saturation, 0f, 1f);

        SaturationLabel.Text = Loc.GetString(
            "is14-analyzer-saturation-short",
            ("percent", (int) MathF.Round(saturation * 100f)));
        SaturationLabel.FontColorOverride = saturation < 0.95f ? Red : Cyan;
    }

    private static readonly Color Muted = Color.FromHex("#7A8B99");
    private static readonly Color Green = Color.FromHex("#3ABB6A");
    private static readonly Color Amber = Color.FromHex("#BB8A3A");
    private static readonly Color Orange = Color.FromHex("#C4783A");
    private static readonly Color Red = Color.FromHex("#C4564E");
    private static readonly Color Cyan = Color.FromHex("#3AAFBB");
}

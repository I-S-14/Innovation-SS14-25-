using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._IS14.Cyborgs.UI;

/// <summary>
/// Picks what a cyborg hypospray or shaker synthesizes.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CyborgReagentWindow : FancyWindow
{
    public event Action<string>? ReagentSelected;

    public CyborgReagentWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void Populate(IReadOnlyList<(string Id, string Name, Color Color)> reagents, string? selected)
    {
        ReagentList.RemoveAllChildren();
        foreach (var (id, name, color) in reagents)
        {
            var row = new CyborgReagentRow();
            row.SetReagent(name, color, id == selected);
            row.OnSelected += () => ReagentSelected?.Invoke(id);
            ReagentList.AddChild(row);
        }
    }
}

using Content.Shared._IS14.Cyborgs.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._IS14.Cyborgs.UI;

/// <summary>
/// A toggle button showing a cyborg skin, with an optional caption. Used for both models and skins.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CyborgPickEntry : ContainerButton
{
    public CyborgPickEntry()
    {
        RobustXamlLoader.Load(this);
    }

    public void Set(CyborgSkinPrototype? skin, float scale, string name, bool caption)
    {
        Preview.SetSkin(skin, scale);
        NameLabel.Text = name;
        NameLabel.Visible = caption;
        ToolTip = caption ? null : name;
    }
}

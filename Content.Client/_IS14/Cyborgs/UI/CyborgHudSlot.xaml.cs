namespace Content.Client._IS14.Cyborgs.UI;

/// <summary>
/// A square of the cyborg HUD: a tgstation screen_cyborg background with an item drawn over it.
/// Used both for the three tool slots and for the cells of the tool grid.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CyborgHudSlot : ContainerButton
{
    public static readonly ResPath HudRsi = new("/Textures/_IS14/Interface/Cyborgs/screen_cyborg.rsi");

    [Dependency] private readonly IEntityManager _entMan = default!;

    /// <summary>
    /// Right click on the square.
    /// </summary>
    public event Action<CyborgHudSlot>? OnSecondaryPressed;

    /// <summary>
    /// Shift click, the usual examine binding.
    /// </summary>
    public event Action<CyborgHudSlot>? OnExaminePressed;

    /// <summary>
    /// Alt click, the alternative interaction like toggling a bag's magnet.
    /// </summary>
    public event Action<CyborgHudSlot>? OnAltPressed;

    public EntityUid? Entity { get; private set; }

    /// <summary>
    /// Draw the held tool's <see cref="CyborgHudGaugeComponent"/>: only the tool slots do, not the grid.
    /// </summary>
    public bool ShowGauge { get; set; }

    private string? _gaugeState;

    private string? _backgroundState;

    private readonly SpriteSystem _sprite;
    private readonly SharedSolutionContainerSystem _solution;
    private readonly UseDelaySystem _useDelay;

    public CyborgHudSlot()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _entMan.System<SpriteSystem>();
        _solution = _entMan.System<SharedSolutionContainerSystem>();
        _useDelay = _entMan.System<UseDelaySystem>();
    }

    public void SetBackground(string state)
    {
        if (_backgroundState == state)
            return;

        _backgroundState = state;
        Background.Texture = _sprite.Frame0(new SpriteSpecifier.Rsi(HudRsi, state));
    }

    /// <summary>
    /// Tints the background green, for tools that are out in a slot.
    /// </summary>
    public void SetHighlight(bool highlight)
    {
        Background.ModulateSelfOverride = highlight ? Color.FromHex("#7CFF7C") : null;
    }

    public void SetEntity(EntityUid? entity)
    {
        Entity = entity;
        ItemView.SetEntity(entity);
        ItemView.Visible = entity != null;
        UpdateGauge();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateGauge();
        UpdateCooldown();
    }

    private void UpdateCooldown()
    {
        if (Entity is not { } item || !_entMan.TryGetComponent<UseDelayComponent>(item, out var useDelay))
        {
            CooldownDisplay.Visible = false;
            return;
        }

        var delay = _useDelay.GetLastEndingDelay((item, useDelay));
        CooldownDisplay.Visible = true;
        CooldownDisplay.FromTime(delay.StartTime, delay.EndTime);
    }

    private void UpdateGauge()
    {
        if (!ShowGauge || Entity is not { } tool ||
            !_entMan.TryGetComponent<CyborgHudGaugeComponent>(tool, out var gauge) || gauge.States.Count < 2 ||
            !_solution.TryGetSolution(tool, gauge.Solution, out _, out var solution))
        {
            Gauge.Visible = false;
            _gaugeState = null;
            return;
        }

        // Each state covers the band below it: with 0/25/50/75/100, the 100 state shows from 75% up.
        var bands = gauge.States.Count - 1;
        var fraction = solution.FillFraction;
        var level = fraction <= 0f ? 0 : Math.Clamp((int) MathF.Ceiling(fraction * bands - 0.0001f), 1, bands);
        var state = gauge.States[level];

        Gauge.Visible = true;
        if (_gaugeState == state)
            return;

        _gaugeState = state;
        var rsi = SpriteSpecifierSerializer.TextureRoot / gauge.Sprite;
        Gauge.Texture = _sprite.Frame0(new SpriteSpecifier.Rsi(rsi, state));
    }

    protected override void KeyBindDown(GUIBoundKeyEventArgs args)
    {
        if (args.Function == ContentKeyFunctions.ExamineEntity)
        {
            OnExaminePressed?.Invoke(this);
            args.Handle();
            return;
        }

        if (args.Function == ContentKeyFunctions.AltActivateItemInWorld && OnAltPressed != null)
        {
            OnAltPressed.Invoke(this);
            args.Handle();
            return;
        }

        if (args.Function == EngineKeyFunctions.UseSecondary)
        {
            OnSecondaryPressed?.Invoke(this);
            args.Handle();
            return;
        }

        base.KeyBindDown(args);
    }
}

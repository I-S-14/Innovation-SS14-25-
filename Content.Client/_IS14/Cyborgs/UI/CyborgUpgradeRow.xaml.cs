using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._IS14.Cyborgs.UI;

/// <summary>
/// An installed upgrade board in the maintenance window, with a button to pull it out.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CyborgUpgradeRow : BoxContainer
{
    public event Action? OnRemove;

    public CyborgUpgradeRow()
    {
        RobustXamlLoader.Load(this);
        RemoveButton.OnPressed += _ => OnRemove?.Invoke();
    }

    public void SetBoard(EntityUid? board, string name)
    {
        BoardView.SetEntity(board);
        NameLabel.Text = name;
    }
}

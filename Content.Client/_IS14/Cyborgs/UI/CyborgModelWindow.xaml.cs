using Content.Client.UserInterface.Controls;
using Content.Shared._IS14.Cyborgs.Prototypes;
using Content.Shared.Guidebook;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._IS14.Cyborgs.UI;

/// <summary>
/// Picks a model and its skin, laid out like the upstream borg type menu.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CyborgModelWindow : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _proto = default!;

    private const float ListScale = 1.5f;
    private const float SkinScale = 2f;
    private const float BigScale = 3f;

    private static readonly List<ProtoId<GuideEntryPrototype>> GuidebookEntries = new() { "Cyborgs", "Robotics" };

    private CyborgModelPrototype? _model;
    private CyborgSkinPrototype? _skin;

    public event Action<ProtoId<CyborgModelPrototype>, ProtoId<CyborgSkinPrototype>?>? Confirmed;

    public CyborgModelWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        HelpGuidebookIds = GuidebookEntries;
        ConfirmButton.OnPressed += _ => OnConfirm();
    }

    /// <summary>
    /// Fills the model list. With a single model it is picked straight away.
    /// </summary>
    public void Populate(IReadOnlyList<CyborgModelPrototype> models, ProtoId<CyborgSkinPrototype>? currentSkin = null)
    {
        ModelList.RemoveAllChildren();

        var group = new ButtonGroup();
        CyborgPickEntry? only = null;
        foreach (var model in models)
        {
            var entry = new CyborgPickEntry { Group = group };
            entry.Set(FirstSkin(model), ListScale, Loc.GetString(model.Name), caption: true);
            entry.OnPressed += _ => SelectModel(model, null);
            ModelList.AddChild(entry);
            only = entry;
        }

        if (models.Count == 1 && only != null)
        {
            only.Pressed = true;
            SelectModel(models[0], currentSkin);
        }
    }

    private void SelectModel(CyborgModelPrototype model, ProtoId<CyborgSkinPrototype>? preferredSkin)
    {
        _model = model;

        InfoPlaceholder.Visible = false;
        InfoContents.Visible = true;
        NameLabel.Text = Loc.GetString(model.Name);
        DescriptionLabel.SetMessage(model.Description is { } desc ? Loc.GetString(desc) : string.Empty);

        SkinList.RemoveAllChildren();
        var group = new ButtonGroup();
        CyborgSkinPrototype? selected = null;
        CyborgPickEntry? selectedEntry = null;
        foreach (var skinId in model.Skins)
        {
            if (!_proto.TryIndex(skinId, out var skin))
                continue;

            var entry = new CyborgPickEntry { Group = group };
            entry.Set(skin, SkinScale, Loc.GetString(skin.Name), caption: false);
            entry.OnPressed += _ => SelectSkin(skin);
            SkinList.AddChild(entry);

            // The current skin if there is one, the first otherwise.
            if (selected == null || skinId == preferredSkin)
            {
                selected = skin;
                selectedEntry = entry;
            }
        }

        SkinSection.Visible = SkinList.ChildCount > 1;

        if (selectedEntry != null)
            selectedEntry.Pressed = true;

        SelectSkin(selected);
    }

    private void SelectSkin(CyborgSkinPrototype? skin)
    {
        _skin = skin;
        BigPreview.SetSkin(skin, BigScale);
        SkinLabel.Text = skin == null ? string.Empty : Loc.GetString(skin.Name);
        ConfirmButton.Disabled = _model == null;
    }

    private void OnConfirm()
    {
        if (_model == null)
            return;

        Confirmed?.Invoke(_model.ID, _skin?.ID);
    }

    private CyborgSkinPrototype? FirstSkin(CyborgModelPrototype model)
    {
        return model.Skins.Count > 0 && _proto.TryIndex(model.Skins[0], out var skin) ? skin : null;
    }
}

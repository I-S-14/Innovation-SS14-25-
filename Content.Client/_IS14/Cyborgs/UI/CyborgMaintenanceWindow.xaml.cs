using Content.Client.UserInterface.Controls;
using Content.Shared._IS14.Cyborgs;
using Content.Shared._IS14.Cyborgs.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._IS14.Cyborgs.UI;

/// <summary>
/// What someone sees through the open cover of a cyborg: cell, chassis, brain and upgrade boards.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CyborgMaintenanceWindow : FancyWindow
{
    [Dependency] private readonly IEntityManager _entMan = default!;

    public event Action? EjectBrainPressed;
    public event Action? EjectCellPressed;
    public event Action<NetEntity>? RemoveUpgradePressed;

    private EntityUid _cyborg;

    public CyborgMaintenanceWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        EjectBrainButton.OnPressed += _ => EjectBrainPressed?.Invoke();
        EjectCellButton.OnPressed += _ => EjectCellPressed?.Invoke();
    }

    public void SetCyborg(EntityUid cyborg)
    {
        _cyborg = cyborg;
        CyborgSprite.SetEntity(cyborg);
        NameLabel.Text = _entMan.GetComponent<MetaDataComponent>(cyborg).EntityName;
    }

    public void UpdateState(CyborgMaintenanceBuiState state)
    {
        NameLabel.Text = _entMan.GetComponentOrNull<MetaDataComponent>(_cyborg)?.EntityName ?? string.Empty;
        ModelLabel.Text = state.Model ?? Loc.GetString("cyborg-hud-no-model");

        var brain = _entMan.GetComponentOrNull<CyborgComponent>(_cyborg)?.BrainEntity;
        BrainView.SetEntity(brain);
        BrainView.Visible = brain != null;
        BrainLabel.Text = state.Brain != null
            ? Loc.GetString("cyborg-maintenance-eject-brain", ("brain", state.Brain))
            : Loc.GetString("cyborg-maintenance-no-brain");
        EjectBrainButton.Disabled = state.Brain == null;

        ChargeBar.Value = state.Charge ?? 0f;
        ChargeLabel.Text = state.Charge is { } charge
            ? Loc.GetString("cyborg-maintenance-charge", ("percent", (int) MathF.Round(charge * 100)))
            : Loc.GetString("cyborg-maintenance-no-cell");
        EjectCellButton.Disabled = state.Charge == null;

        UpgradeList.RemoveAllChildren();
        foreach (var (board, name) in state.Upgrades)
        {
            var row = new CyborgUpgradeRow();
            row.SetBoard(_entMan.GetEntity(board), name);
            row.OnRemove += () => RemoveUpgradePressed?.Invoke(board);
            UpgradeList.AddChild(row);
        }

        NoUpgradesLabel.Visible = state.Upgrades.Count == 0;
        UpgradeCounter.Text = Loc.GetString("cyborg-maintenance-upgrade-count", ("count", state.Upgrades.Count));
    }
}

using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._IS14.Cyborgs.UI;

/// <summary>
/// A reagent the cyborg can synthesize: its colour and a button to pick it.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CyborgReagentRow : BoxContainer
{
    public event Action? OnSelected;

    public CyborgReagentRow()
    {
        RobustXamlLoader.Load(this);
        SelectButton.OnPressed += _ => OnSelected?.Invoke();
    }

    public void SetReagent(string name, Color color, bool selected)
    {
        SelectButton.Text = name;
        SelectButton.Pressed = selected;
        Swatch.PanelOverride = new StyleBoxFlat { BackgroundColor = color };
    }
}

using System.Numerics;
using Content.Shared._IS14.Cyborgs.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._IS14.Cyborgs.UI;

/// <summary>
/// South-facing still of a cyborg skin: the body with the lit eyes on top.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CyborgSkinPreview : Control
{
    [Dependency] private readonly IEntitySystemManager _systems = default!;

    public CyborgSkinPreview()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void SetSkin(CyborgSkinPrototype? skin, float scale)
    {
        var sprite = _systems.GetEntitySystem<SpriteSystem>();
        var textureScale = new Vector2(scale, scale);

        Body.TextureScale = textureScale;
        Eyes.TextureScale = textureScale;
        Body.Texture = skin == null ? null : sprite.Frame0(skin.Icon);
        Eyes.Texture = skin?.EyesState == null
            ? null
            : sprite.Frame0(new SpriteSpecifier.Rsi(skin.Sprite, skin.EyesState));

        // Sized to the body so that bigger skins don't get cut off.
        MinSize = Body.Texture == null ? Vector2.Zero : (Vector2) Body.Texture.Size * scale;
    }
}

using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._IS14.Research;
using Content.Shared.Research.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._IS14.Research;

/// <summary>
/// A department's order terminal: what the department is waiting for, what it pays for it, and
/// the topics it can commission.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class IS14WorkOrderWindow : FancyWindow
{
    private readonly IEntityManager _entManager;
    private readonly IPrototypeManager _protoManager;
    private readonly SpriteSystem _sprites;

    public event Action<string>? OnOrderPressed;

    public event Action? OnCancelPressed;

    public IS14WorkOrderWindow()
    {
        RobustXamlLoader.Load(this);

        _entManager = IoCManager.Resolve<IEntityManager>();
        _protoManager = IoCManager.Resolve<IPrototypeManager>();
        _sprites = _entManager.System<SpriteSystem>();

        CancelButton.OnPressed += _ => OnCancelPressed?.Invoke();
    }

    public void UpdateState(IS14WorkOrderUiState state)
    {
        DepartmentLabel.Text = state.DepartmentName;

        var pointName = _protoManager.TryIndex(state.PointType, out ResearchPointTypePrototype? type)
            ? Loc.GetString(type.Name)
            : state.PointType;

        TermsLabel.Text = Loc.GetString("is14-workorder-terms",
            ("bonus", state.Bonus),
            ("type", pointName),
            ("payment", state.Payment));

        BudgetLabel.Text = Loc.GetString("is14-workorder-budget", ("balance", state.Budget));

        CancelButton.Visible = state.Order != null;

        if (state.Order != null && _protoManager.TryIndex(state.Order, out TechnologyPrototype? ordered))
        {
            OrderLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(
                $"[color=#cca031]{Loc.GetString(ordered.Name).Replace("[", "[[")}[/color]"));
        }
        else
        {
            OrderLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(
                $"[color=#9a9a9a]{Loc.GetString("is14-workorder-none")}[/color]"));
        }

        BuildRows(state);
    }

    /// <summary>
    /// Everything the NIC could still be asked for: our branches, nothing hidden, nothing
    /// already delivered. Rebuilt on every push — the list is short and the state is rare.
    /// </summary>
    private void BuildRows(IS14WorkOrderUiState state)
    {
        RowContainer.RemoveAllChildren();

        var unlocked = new HashSet<string>(state.Unlocked);

        var technologies = _protoManager.EnumeratePrototypes<TechnologyPrototype>()
            .Where(tech => !tech.Hidden
                           && !unlocked.Contains(tech.ID)
                           && (state.Branches.Count == 0 || state.Branches.Contains(tech.Discipline.Id)))
            .OrderBy(tech => tech.Tier)
            .ThenBy(tech => Loc.GetString(tech.Name))
            .ToList();

        foreach (var tech in technologies)
        {
            var branch = _protoManager.TryIndex(tech.Discipline, out TechDisciplinePrototype? discipline)
                ? discipline
                : null;

            var row = new IS14WorkOrderRow();
            row.SetRow(tech, branch, state.Order == tech.ID, _sprites);
            row.OnOrder += id =>
            {
                if (state.Order == id)
                    OnCancelPressed?.Invoke();
                else
                    OnOrderPressed?.Invoke(id);
            };

            RowContainer.AddChild(row);
        }
    }
}

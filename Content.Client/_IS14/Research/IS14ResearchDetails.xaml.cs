using System.Linq;
using Content.Shared._IS14.Research;
using Content.Shared.Lathe;
using Content.Shared.Research.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._IS14.Research;

/// <summary>
/// The panel beside the map: what the selected technology costs, what it needs, what it changes
/// on the station and what it lets the lathes print.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class IS14ResearchDetails : BoxContainer
{
    private readonly IEntityManager _entManager;
    private readonly IPrototypeManager _protoManager;
    private readonly SpriteSystem _sprites;
    private readonly SharedLatheSystem _lathe;

    private string? _technologyId;

    public event Action<string>? OnResearchPressed;

    public event Action? OnClosePressed;

    /// <summary>
    /// Another technology named on this card was clicked: a prerequisite or the alternative a
    /// fork rules out. The console answers by opening that one and centring the map on it.
    /// </summary>
    public event Action<string>? OnTechnologyPressed;

    /// <summary>
    /// Whether a technology is actually drawn on the map. A card for something the station
    /// cannot see — a topic still hidden — stays inert instead of becoming a dead link.
    /// </summary>
    public Func<string, bool>? CanOpen;

    public IS14ResearchDetails()
    {
        RobustXamlLoader.Load(this);

        _entManager = IoCManager.Resolve<IEntityManager>();
        _protoManager = IoCManager.Resolve<IPrototypeManager>();
        _sprites = _entManager.System<SpriteSystem>();
        _lathe = _entManager.System<SharedLatheSystem>();

        HintLabel.Text = Loc.GetString("is14-research-map-select-hint");
        NoPrereqLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(Dim(Loc.GetString("is14-research-map-no-prereqs"))));

        ResearchButton.OnPressed += _ =>
        {
            if (_technologyId != null)
                OnResearchPressed?.Invoke(_technologyId);
        };

        CloseButton.OnPressed += _ => OnClosePressed?.Invoke();
    }

    public void Clear()
    {
        _technologyId = null;
        Body.Visible = false;
        HintLabel.Visible = true;
    }

    public void Show(
        TechnologyPrototype tech,
        IS14TechDataPrototype? data,
        Dictionary<ProtoId<ResearchPointTypePrototype>, int> costs,
        IReadOnlyDictionary<string, int> balances,
        IReadOnlySet<string> unlocked,
        IS14NodeState state,
        bool serverConnected,
        float discount,
        float priority,
        IReadOnlyList<string> exclusiveSiblings)
    {
        _technologyId = tech.ID;
        Body.Visible = true;
        HintLabel.Visible = false;

        NameLabel.SetMessage(Loc.GetString(tech.Name));
        TechnologyIcon.Texture = _sprites.Frame0(tech.Icon);

        var discipline = _protoManager.TryIndex(tech.Discipline, out TechDisciplinePrototype? disciplineProto)
            ? disciplineProto
            : null;

        var tier = Loc.GetString("is14-research-card-tier", ("tier", tech.Tier));

        BranchLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(Dim(discipline != null
            ? $"{Loc.GetString(discipline.Name)} · {tier}"
            : tier)));

        DisciplineIcon.Visible = discipline != null;
        if (discipline != null)
        {
            DisciplineIcon.Texture = _sprites.Frame0(discipline.Icon);
            DisciplineIcon.ModulateSelfOverride = discipline.Color;
        }

        SummaryLabel.Visible = data?.Summary != null;
        if (data?.Summary != null)
            SummaryLabel.SetMessage(Loc.GetString(data.Summary.Value));

        ShowCost(costs, balances);

        DiscountLabel.Visible = discount > 0f;
        if (discount > 0f)
        {
            DiscountLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(Colored(
                Loc.GetString("is14-research-map-discount", ("percent", (int) MathF.Round(discount * 100))),
                "#7ecd48")));
        }

        PriorityLabel.Visible = priority > 0f;
        if (priority > 0f)
        {
            PriorityLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(Colored(
                Loc.GetString("is14-research-map-priority", ("percent", (int) MathF.Round(priority * 100))),
                "#e8c547")));
        }

        ShowEffects(data);
        ShowBreakthrough(data, state);
        ShowExclusive(exclusiveSiblings, unlocked);
        ShowPrerequisites(tech, unlocked);
        ShowUnlocks(tech);
        ShowStatus(state, serverConnected);
    }

    private void ShowCost(
        Dictionary<ProtoId<ResearchPointTypePrototype>, int> costs,
        IReadOnlyDictionary<string, int> balances)
    {
        CostContainer.RemoveAllChildren();

        foreach (var (typeId, amount) in costs.OrderBy(pair => pair.Key.Id))
        {
            if (!_protoManager.TryIndex(typeId, out ResearchPointTypePrototype? type))
                continue;

            balances.TryGetValue(typeId.Id, out var balance);

            var chip = new IS14CostChip();
            chip.SetChip(type, amount, balance >= amount, _sprites);
            CostContainer.AddChild(chip);
        }
    }

    /// <summary>
    /// Prerequisites as cards: branch colour on the strip, green when already researched, so it
    /// is obvious which one is still missing.
    /// </summary>
    private void ShowPrerequisites(TechnologyPrototype tech, IReadOnlySet<string> unlocked)
    {
        PrereqContainer.RemoveAllChildren();

        NoPrereqLabel.Visible = tech.TechnologyPrerequisites.Count == 0;
        PrereqContainer.Visible = tech.TechnologyPrerequisites.Count > 0;

        foreach (var prereqId in tech.TechnologyPrerequisites)
        {
            if (!_protoManager.TryIndex(prereqId, out TechnologyPrototype? prereq))
                continue;

            var researched = unlocked.Contains(prereq.ID);
            var color = researched
                ? Color.FromHex("#5ec45e")
                : _protoManager.TryIndex(prereq.Discipline, out TechDisciplinePrototype? branch)
                    ? branch.Color
                    : Color.Gray;

            var name = Loc.GetString(prereq.Name);
            var tooltip = researched
                ? Loc.GetString("is14-research-map-prereq-done")
                : Loc.GetString("is14-research-map-prereq-missing");

            var card = new IS14MiniCard();
            card.SetCard(name, _sprites.Frame0(prereq.Icon), color, Linkable(prereq.ID, tooltip));
            Link(card, prereq.ID);
            PrereqContainer.AddChild(card);
        }
    }

    /// <summary>
    /// The sample a breakthrough is paid for with. Named and pictured, because the whole point
    /// is that the player can read this and go find the thing.
    /// </summary>
    private void ShowBreakthrough(IS14TechDataPrototype? data, IS14NodeState state)
    {
        BreakthroughContainer.RemoveAllChildren();

        var requirement = data?.Breakthrough;
        var any = requirement != null;

        BreakthroughHeader.Visible = any;
        BreakthroughDivider.Visible = any;
        BreakthroughContainer.Visible = any;
        BreakthroughStatusLabel.Visible = any;

        if (requirement == null)
            return;

        Texture? icon = null;

        var iconProto = requirement.Icon?.Id
                        ?? (requirement.Samples.Count > 0 ? requirement.Samples[0].Id : null);

        if (iconProto != null && _protoManager.TryIndex(iconProto, out EntityPrototype? sampleProto))
            icon = _sprites.Frame0(sampleProto);

        var card = new IS14MiniCard();
        card.SetCard(
            Loc.GetString(requirement.Name),
            icon,
            Color.FromHex("#9a6ef0"),
            requirement.Hint != null ? Loc.GetString(requirement.Hint.Value) : null);
        BreakthroughContainer.AddChild(card);

        var done = state != IS14NodeState.NeedsSample;

        BreakthroughStatusLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(Colored(
            Loc.GetString(done
                ? "is14-research-map-breakthrough-done"
                : "is14-research-map-breakthrough-missing"),
            done ? "#7ecd48" : "#9a6ef0")));
    }

    /// <summary>The alternatives this topic rules out, and which one has already closed it.</summary>
    private void ShowExclusive(IReadOnlyList<string> siblings, IReadOnlySet<string> unlocked)
    {
        ExclusiveContainer.RemoveAllChildren();

        var any = siblings.Count > 0;

        ExclusiveHeader.Visible = any;
        ExclusiveDivider.Visible = any;
        ExclusiveContainer.Visible = any;

        foreach (var siblingId in siblings)
        {
            if (!_protoManager.TryIndex(siblingId, out TechnologyPrototype? sibling))
                continue;

            var taken = unlocked.Contains(sibling.ID);

            var card = new IS14MiniCard();
            card.SetCard(
                Loc.GetString(sibling.Name),
                _sprites.Frame0(sibling.Icon),
                taken ? Color.FromHex("#a33b40") : Color.FromHex("#9a9a9a"),
                Linkable(sibling.ID, Loc.GetString(taken
                    ? "is14-research-map-exclusive-taken"
                    : "is14-research-map-exclusive-open")));
            Link(card, sibling.ID);
            ExclusiveContainer.AddChild(card);
        }
    }

    private void ShowEffects(IS14TechDataPrototype? data)
    {
        EffectsContainer.RemoveAllChildren();

        var effects = data?.Effects ?? new List<IS14TechEffect>();
        var lines = effects.Where(effect => effect.Description != null).ToList();

        EffectsHeader.Visible = lines.Count > 0;
        EffectsContainer.Visible = lines.Count > 0;

        foreach (var effect in lines)
        {
            var label = new RichTextLabel { HorizontalExpand = true };
            label.SetMessage($"· {Loc.GetString(effect.Description!.Value)}");
            EffectsContainer.AddChild(label);
        }
    }

    /// <summary>Unlocked recipes as cards with the item's own sprite and its description.</summary>
    private void ShowUnlocks(TechnologyPrototype tech)
    {
        UnlocksContainer.RemoveAllChildren();

        var any = tech.RecipeUnlocks.Count > 0;
        UnlocksHeader.Visible = any;
        UnlocksDivider.Visible = any;
        UnlocksContainer.Visible = any;

        foreach (var recipeId in tech.RecipeUnlocks)
        {
            if (!_protoManager.TryIndex(recipeId, out LatheRecipePrototype? recipe))
                continue;

            Texture? icon = null;

            if (recipe.Result is { } result && _protoManager.TryIndex(result, out EntityPrototype? resultProto))
                icon = _sprites.Frame0(resultProto);

            var card = new IS14MiniCard();
            card.SetCard(_lathe.GetRecipeName(recipe), icon, Color.FromHex("#4972A1"), _lathe.GetRecipeDescription(recipe));
            UnlocksContainer.AddChild(card);
        }
    }

    private void ShowStatus(IS14NodeState state, bool serverConnected)
    {
        ResearchButton.Visible = state != IS14NodeState.Researched;
        ResearchButton.Disabled = state != IS14NodeState.Available || !serverConnected;

        if (!serverConnected)
        {
            SetStatus("is14-research-card-no-server", "#c78d3a");
            return;
        }

        switch (state)
        {
            case IS14NodeState.Researched:
                SetStatus("is14-research-card-researched", "#7ecd48");
                break;
            case IS14NodeState.Available:
                SetStatus("is14-research-card-ready", "#7ecd48");
                break;
            case IS14NodeState.Unaffordable:
                SetStatus("is14-research-card-needs-data", "#c07a7a");
                break;
            case IS14NodeState.NeedsSample:
                SetStatus("is14-research-card-needs-sample", "#9a6ef0");
                break;
            case IS14NodeState.Excluded:
                SetStatus("is14-research-card-excluded", "#9a9a9a");
                break;
            default:
                SetStatus("is14-research-card-needs-prereq-short", "#9a9a9a");
                break;
        }
    }

    private void SetStatus(string locId, string color)
    {
        StatusLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(Colored(Loc.GetString(locId), color)));
    }

    /// <summary>Makes a card naming another technology open it, if the map has that node.</summary>
    private void Link(IS14MiniCard card, string technologyId)
    {
        if (CanOpen?.Invoke(technologyId) == false)
            return;

        card.SetLink(() => OnTechnologyPressed?.Invoke(technologyId));
    }

    /// <summary>Adds the "click me" line to a tooltip, for a card that is in fact clickable.</summary>
    private string Linkable(string technologyId, string tooltip)
    {
        return CanOpen?.Invoke(technologyId) == false
            ? tooltip
            : $"{tooltip}\n{Loc.GetString("is14-research-map-open-hint")}";
    }

    /// <summary>
    /// Rich text wraps where a Label does not, and inside a fixed-width panel wrapping is the
    /// whole point — so colour goes through markup rather than FontColorOverride.
    /// </summary>
    private static string Colored(string text, string color) => $"[color={color}]{Escape(text)}[/color]";

    private static string Dim(string text) => Colored(text, "#9a9a9a");

    /// <summary>Technology names and summaries are free text: brackets must not become markup.</summary>
    private static string Escape(string text) => text.Replace("[", "[[");
}

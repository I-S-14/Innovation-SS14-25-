using Content.Shared._IS14.Research;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._IS14.Research;

/// <summary>One line of the array's log: what it measured and what it was worth.</summary>
[GenerateTypedNameReferences]
public sealed partial class IS14OrdnanceRecordRow : BoxContainer
{
    public event Action<int>? OnPrint;
    public event Action<int>? OnDelete;

    private int _number;

    public IS14OrdnanceRecordRow()
    {
        RobustXamlLoader.Load(this);

        PrintButton.OnPressed += _ => OnPrint?.Invoke(_number);
        DeleteButton.OnPressed += _ => OnDelete?.Invoke(_number);
    }

    public void SetRecord(IS14OrdnanceRecord record)
    {
        _number = record.Number;

        TitleLabel.Text = Loc.GetString("is14-doppler-window-record-title",
            ("number", record.Number),
            ("timestamp", record.Timestamp));

        var (verdict, color) = record.TooClose
            ? (Loc.GetString("is14-doppler-window-verdict-too-close"), "#c07a7a")
            : record.Record
                ? (Loc.GetString("is14-doppler-window-verdict-record", ("amount", record.Payout)), "#7ecd48")
                : (Loc.GetString("is14-doppler-window-verdict-repeat", ("amount", record.Payout)), "#cca031");

        VerdictLabel.Text = verdict;
        VerdictLabel.FontColorOverride = Color.FromHex(color);

        BodyLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(Loc.GetString("is14-doppler-window-record-body",
            ("location", record.Location),
            ("coordinates", record.Coordinates),
            ("distance", (int) record.Distance),
            ("intensity", (int) record.TotalIntensity),
            ("epicenter", record.EpicenterRadius.ToString("F1")),
            ("outer", record.OuterRadius.ToString("F1")),
            ("shockwave", record.ShockwaveRadius.ToString("F1")))));

        RowPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex(record.Record ? "#1d2b1d" : "#1B1B1E"),
            BorderColor = Color.FromHex(record.TooClose ? "#6b3a3a" : record.Record ? "#4a7a4a" : "#3a3a41"),
            BorderThickness = new Thickness(1),
        };
    }
}

using Content.Shared._IS14.Research;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._IS14.Research;

/// <summary>
/// One currency in a price: the number and that currency's icon, tinted with its colour and
/// greyed out when the station cannot cover it.
/// </summary>
/// <remarks>
/// The icon rather than a three-letter tag: on a node packed with two or three currencies the
/// tag is unreadable, while the colour and the icon are recognisable at a glance.
/// </remarks>
[GenerateTypedNameReferences]
public sealed partial class IS14CostChip : BoxContainer
{
    public IS14CostChip()
    {
        RobustXamlLoader.Load(this);
    }

    public void SetChip(ResearchPointTypePrototype type, int amount, bool affordable, SpriteSystem sprites)
    {
        AmountLabel.Text = amount.ToString();

        var color = affordable ? type.Color : Color.FromHex("#8a3a3a");

        ChipPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = color.WithAlpha(0.22f),
            BorderColor = color,
            BorderThickness = new Thickness(1),
        };

        AmountLabel.FontColorOverride = affordable ? Color.White : Color.FromHex("#ff9a9a");

        IconRect.Visible = type.Icon != null;
        if (type.Icon != null)
        {
            IconRect.Texture = sprites.Frame0(type.Icon);
            IconRect.ModulateSelfOverride = affordable ? Color.White : Color.FromHex("#ff9a9a");
        }

        ToolTip = $"{Loc.GetString(type.Name)} ({Loc.GetString(type.ShortName)})";
    }
}

using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._IS14.Research;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._IS14.Research;

/// <summary>
/// The array's log: which way it is pointing, what the station's best blast of each kind was, and
/// every reading it took, newest first.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class IS14DopplerArrayWindow : FancyWindow
{
    public event Action<int>? OnPrint;
    public event Action<int>? OnDelete;

    public IS14DopplerArrayWindow()
    {
        RobustXamlLoader.Load(this);

        HintLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(
            $"[color=#9a9a9a]{Loc.GetString("is14-doppler-window-hint")}[/color]"));
    }

    public void UpdateState(IS14DopplerArrayUiState state)
    {
        FacingLabel.Text = Loc.GetString("is14-doppler-window-facing", ("facing", state.Facing));

        BestLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(state.BestIntensity <= 0f
            ? $"[color=#9a9a9a]{Loc.GetString("is14-doppler-window-no-records")}[/color]"
            : Loc.GetString("is14-doppler-window-best", ("intensity", (int) state.BestIntensity))));

        RecordsContainer.RemoveAllChildren();
        EmptyLabel.Visible = state.Records.Count == 0;

        // Newest first: the reading you just took is the one you came to look at.
        foreach (var record in state.Records.OrderByDescending(entry => entry.Number))
        {
            var row = new IS14OrdnanceRecordRow();
            row.SetRecord(record);
            row.OnPrint += number => OnPrint?.Invoke(number);
            row.OnDelete += number => OnDelete?.Invoke(number);

            RecordsContainer.AddChild(row);
        }
    }
}

using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._IS14.Research;

/// <summary>
/// A one-line entry with a picture: a prerequisite technology, or a recipe the research unlocks.
/// </summary>
/// <remarks>
/// Modelled on Goob's R&amp;D console cards, which read far better than a list of names: the
/// sprite says what the thing is, the colour strip says which branch it came from, and the
/// tooltip carries the detail.
/// </remarks>
[GenerateTypedNameReferences]
public sealed partial class IS14MiniCard : BoxContainer
{
    public IS14MiniCard()
    {
        RobustXamlLoader.Load(this);
    }

    public void SetCard(string name, Texture? icon, Color stripColor, string? tooltip = null)
    {
        NameLabel.SetMessage(name);
        Strip.ModulateSelfOverride = stripColor;

        IconRect.Visible = icon != null;
        if (icon != null)
            IconRect.Texture = icon;

        if (tooltip == null)
            return;

        var control = new Tooltip();
        control.SetMessage(FormattedMessage.FromUnformatted(tooltip));
        Main.TooltipSupplier = _ => control;
    }

    /// <summary>
    /// Turns the card into a link. Cards are inert by default — they are a picture of a
    /// requirement, not a control — but a card naming another technology is worth clicking.
    /// </summary>
    public void SetLink(Action onPressed)
    {
        Main.Disabled = false;
        Main.OnPressed += _ => onPressed();
    }
}

namespace Content.Client._IS14.Research.Editor;

/// <summary>
/// The tree editor: build the research map by hand, check it against the design rules, and write
/// out the files the game reads.
/// </summary>
/// <remarks>
/// Opened with the <c>is14treeeditor</c> command. It starts from the tree that is live in this
/// client, so editing is always a change to something real rather than a blank page, and saving
/// drops three files into the client's user data — the same three the python generator writes, so
/// copying them into <c>Resources/Prototypes/_IS14/Research/</c> is the whole deployment step.
/// </remarks>
[GenerateTypedNameReferences]
public sealed partial class IS14TreeEditorWindow : FancyWindow
{
    private readonly IPrototypeManager _protoManager;
    private readonly IResourceManager _resources;
    private readonly SpriteSystem _sprites;

    private readonly Dictionary<string, IS14EditorNode> _controls = new();
    private readonly List<string> _branches = new();

    private IS14TreeDraft _draft = new();
    private IS14DraftNode? _selected;
    private string _branch = string.Empty;

    public IS14TreeEditorWindow()
    {
        RobustXamlLoader.Load(this);

        var entManager = IoCManager.Resolve<IEntityManager>();

        _protoManager = IoCManager.Resolve<IPrototypeManager>();
        _resources = IoCManager.Resolve<IResourceManager>();
        _sprites = entManager.System<SpriteSystem>();

        foreach (var discipline in _protoManager.EnumeratePrototypes<TechDisciplinePrototype>()
                     .Where(discipline => discipline.ID.StartsWith("IS14"))
                     .OrderBy(discipline => discipline.ID))
        {
            BranchButton.AddItem(Loc.GetString(discipline.Name), _branches.Count);
            _branches.Add(discipline.ID);
        }

        BranchButton.OnItemSelected += args =>
        {
            BranchButton.SelectId(args.Id);
            _branch = _branches[args.Id];
            Rebuild();
        };

        Map.Prerequisites = node => node.Node.Prerequisites;
        Map.OnNodeMoved += OnNodeMoved;
        Map.OnBackgroundPressed += Deselect;
        Map.OnZoomChanged += zoom =>
        {
            if (!MathHelper.CloseTo(ZoomSlider.Value, zoom))
                ZoomSlider.Value = zoom;
        };

        ZoomSlider.OnValueChanged += _ => Map.SetZoom(ZoomSlider.Value);
        CenterButton.OnPressed += _ => Map.Center();

        AddButton.OnPressed += _ => AddNode();
        CloneButton.OnPressed += _ => CloneNode();
        DeleteButton.OnPressed += _ => DeleteNode();
        ReloadButton.OnPressed += _ => LoadFromPrototypes();
        OpenButton.OnPressed += _ => LoadDraft();
        SaveButton.OnPressed += _ => Save();
        FolderButton.OnPressed += _ => OpenFolder();

        Inspector.OnChanged += OnNodeEdited;
        Inspector.OnRenamed += OnNodeRenamed;

        _branch = _branches.Count > 0 ? _branches[0] : string.Empty;
        LoadFromPrototypes();
    }

    private void LoadFromPrototypes()
    {
        _draft = IS14TreeDraft.FromPrototypes(_protoManager);
        _selected = null;
        Rebuild();
        Status($"Загружено из игры: тем {_draft.Nodes.Count}.");
    }

    private void LoadDraft()
    {
        if (!IS14TreeExport.TryLoad(_resources, out var draft))
        {
            Status("Черновика нет — сначала сохраните.");
            return;
        }

        _draft = draft;
        _selected = null;
        Rebuild();
        Status($"Черновик открыт: тем {_draft.Nodes.Count}.");
    }

    private void Save()
    {
        IS14TreeExport.Save(_resources, _draft);
        Status($"Сохранено: тем {_draft.Nodes.Count}, три файла в is14_research_editor — "
               + "кнопка «Папка».");
    }

    private void OpenFolder()
    {
        _resources.UserData.CreateDir(IS14TreeExport.Folder);
        _resources.UserData.OpenOsWindow(IS14TreeExport.Folder);
    }

    /// <summary>Rebuilds the canvas for the branch on screen and re-runs the rules.</summary>
    private void Rebuild()
    {
        Map.ClearNodes();
        _controls.Clear();

        foreach (var node in _draft.InBranch(_branch))
        {
            var control = new IS14EditorNode();

            control.Initialize(node, _sprites);
            control.OnPressed += OnNodePressed;
            control.OnDragged += Map.Drag;
            control.OnReleased += Map.StopDrag;

            _controls[node.Id] = control;
            Map.Place(control, node.Position);
        }

        if (_selected != null && _controls.TryGetValue(_selected.Id, out var current))
            current.SetSelected(true);

        Validate();
    }

    private void OnNodePressed(IS14EditorNode control)
    {
        Select(control.Node);

        // The press is also the start of a drag: the window feeds moves to the map until the
        // button comes back up.
        Map.BeginDrag(control);
    }

    private void Select(IS14DraftNode node)
    {
        if (_selected != null && _controls.TryGetValue(_selected.Id, out var previous))
            previous.SetSelected(false);

        _selected = node;

        if (_controls.TryGetValue(node.Id, out var control))
            control.SetSelected(true);

        Inspector.Show(node, _draft);
    }

    private void Deselect()
    {
        if (_selected != null && _controls.TryGetValue(_selected.Id, out var control))
            control.SetSelected(false);

        _selected = null;
        Inspector.Clear();
    }

    private void OnNodeMoved(IS14EditorNode control, Vector2i cell)
    {
        control.Node.Position = cell;

        if (_selected == control.Node)
            Inspector.Show(control.Node, _draft);

        Validate();
    }

    private void OnNodeEdited()
    {
        if (_selected == null)
            return;

        // The branch or the cell may have changed, which the canvas cannot guess.
        if (_selected.Discipline != _branch)
        {
            var moved = _selected;
            Rebuild();
            Status($"{moved.Id} переехала в другую ветку.");
            return;
        }

        if (_controls.TryGetValue(_selected.Id, out var control))
        {
            control.Refresh(_sprites);
            Map.SetCell(control, _selected.Position);
        }
        else
        {
            Rebuild();
        }

        Validate();
    }

    /// <summary>A rename has to drag every reference to the old id along with it.</summary>
    private void OnNodeRenamed(string old, string current)
    {
        foreach (var node in _draft.Nodes)
        {
            for (var index = 0; index < node.Prerequisites.Count; index++)
            {
                if (node.Prerequisites[index] == old)
                    node.Prerequisites[index] = current;
            }
        }

        Rebuild();
        Status($"{old} → {current}, предпосылки переписаны.");
    }

    private void AddNode()
    {
        var node = new IS14DraftNode
        {
            Id = UniqueId("IS14NewTopic"),
            Discipline = _branch,
            Position = FreeCell(),
            Costs = { ["Science"] = 30 },
        };

        if (_selected != null)
        {
            // Added while something is selected: the new topic continues from it, which is how
            // a ray is actually drawn.
            node.Prerequisites.Add(_selected.Id);
            node.Tier = Math.Clamp(_selected.Tier, 1, 5);
            node.IconSprite = _selected.IconSprite;
            node.IconState = _selected.IconState;
        }

        _draft.Nodes.Add(node);
        Rebuild();
        Select(node);
        Status($"Добавлена {node.Id}. Переименуйте её и поставьте цену.");
    }

    private void CloneNode()
    {
        if (_selected == null)
        {
            Status("Нечего дублировать: выберите тему.");
            return;
        }

        var clone = _selected.Clone();

        clone.Id = UniqueId(_selected.Id);
        clone.Position = FreeCell();

        _draft.Nodes.Add(clone);
        Rebuild();
        Select(clone);
        Status($"Создана копия {clone.Id}.");
    }

    private void DeleteNode()
    {
        if (_selected == null)
        {
            Status("Нечего удалять: выберите тему.");
            return;
        }

        var id = _selected.Id;

        _draft.Nodes.Remove(_selected);

        foreach (var node in _draft.Nodes)
        {
            node.Prerequisites.RemoveAll(prereq => prereq == id);
        }

        Deselect();
        Rebuild();
        Status($"{id} удалена, ссылки на неё убраны.");
    }

    private string UniqueId(string wanted)
    {
        if (_draft.Find(wanted) == null)
            return wanted;

        for (var index = 2; ; index++)
        {
            var candidate = $"{wanted}{index}";

            if (_draft.Find(candidate) == null)
                return candidate;
        }
    }

    /// <summary>First empty cell near the selection, so a new node never lands on another.</summary>
    private Vector2i FreeCell()
    {
        var taken = _draft.InBranch(_branch).Select(node => node.Position).ToHashSet();
        var start = _selected?.Position ?? Vector2i.Zero;

        for (var radius = 1; radius < 24; radius++)
        {
            for (var x = -radius; x <= radius; x++)
            {
                for (var y = -radius; y <= radius; y++)
                {
                    var cell = start + new Vector2i(x, y);

                    if (!taken.Contains(cell))
                        return cell;
                }
            }
        }

        return start;
    }

    /// <summary>Runs the design rules and paints the result: red borders and a list below.</summary>
    private void Validate()
    {
        var problems = IS14TreeValidator.Validate(_draft, _protoManager);
        var broken = problems.Where(problem => problem.Fatal).Select(problem => problem.NodeId).ToHashSet();

        foreach (var (id, control) in _controls)
        {
            control.SetBroken(broken.Contains(id));
        }

        ProblemContainer.RemoveAllChildren();

        var fatal = problems.Count(problem => problem.Fatal);

        if (problems.Count == 0)
        {
            ProblemContainer.AddChild(Line("Правила дерева выполнены.", "#7ecd48"));

            return;
        }

        ProblemContainer.AddChild(new Label
        {
            Text = $"Ошибок: {fatal}, предупреждений: {problems.Count - fatal}",
            StyleClasses = { "LabelSmall" },
        });

        foreach (var problem in problems.OrderByDescending(problem => problem.Fatal).Take(40))
        {
            ProblemContainer.AddChild(Line(
                $"{(problem.Fatal ? "✖" : "⚠")} {problem.NodeId}: {problem.Message}",
                problem.Fatal ? "#c07a7a" : "#c78d3a"));
        }
    }

    /// <summary>One wrapped, coloured line of the problem list.</summary>
    private static RichTextLabel Line(string text, string color)
    {
        var label = new RichTextLabel { HorizontalExpand = true };

        label.SetMessage(FormattedMessage.FromMarkupOrThrow($"[color={color}]{text.Replace("[", "[[")}[/color]"));

        return label;
    }

    private void Status(string text)
    {
        StatusLabel.Text = text;
    }

    /// <summary>
    /// Keeps the window still while the canvas is being dragged: a FancyWindow treats its whole
    /// body as a move handle, which would drag the editor around instead of the tree.
    /// </summary>
    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        var mode = base.GetDragModeFor(relativeMousePos);

        if (mode != DragMode.Move)
            return mode;

        return Map.GlobalRect.Contains(GlobalPosition + relativeMousePos) ? DragMode.None : mode;
    }

    protected override void MouseMove(GUIMouseMoveEventArgs args)
    {
        base.MouseMove(args);

        // Moves land on whatever control is under the cursor — usually a node — so the window
        // forwards them; the map ignores them unless something is actually being dragged.
        Map.Drag(args.Relative);
    }

    protected override void KeyBindUp(GUIBoundKeyEventArgs args)
    {
        base.KeyBindUp(args);

        if (args.Function == EngineKeyFunctions.UIClick || args.Function == EngineKeyFunctions.UIRightClick)
            Map.StopDrag();
    }
}

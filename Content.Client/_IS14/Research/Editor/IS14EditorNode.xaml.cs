using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;

namespace Content.Client._IS14.Research.Editor;

/// <summary>
/// One draft topic on the editor's map: the icon it will carry in the console, its name, and a
/// border that says whether it is selected or broken.
/// </summary>
/// <remarks>
/// Deliberately not the console's <c>IS14ResearchNode</c>: that one is driven by a prototype and
/// colours itself by what the station can afford, neither of which exists while editing. Here
/// the colour means "valid / selected / has a problem", and the control has to be draggable.
/// </remarks>
[GenerateTypedNameReferences]
public sealed partial class IS14EditorNode : PanelContainer
{
    public const int Size = 64;

    /// <summary>Distance between map cells, the node itself included.</summary>
    public const int ColumnStride = 96;

    public const int RowStride = 78;

    public IS14DraftNode Node = default!;

    public bool Selected;

    public bool Broken;

    /// <summary>Pressed with the left button: the editor selects it and may start a drag.</summary>
    public event Action<IS14EditorNode>? OnPressed;

    /// <summary>
    /// The button came back up on this node: the drag is over.
    /// </summary>
    /// <remarks>
    /// The node has to report this itself. The engine delivers a keybind-up only to the control
    /// that took the keybind-down and stops bubbling at the first <c>MouseFilterMode.Stop</c>,
    /// which is this node — so the window above never hears the release and, without this event,
    /// the tile would keep following the cursor after the button was let go.
    /// </remarks>
    public event Action? OnReleased;

    /// <summary>
    /// The cursor moved while this node held the press: how far, in its own coordinates.
    /// </summary>
    /// <remarks>
    /// Same routing story as the release. While a button is held the engine sends every mouse
    /// move to the control that took the press and stops at the first
    /// <c>MouseFilterMode.Stop</c> — this node — so the window never sees the movement and the
    /// tile would sit still for as long as the button is down. Forwarded from here instead.
    /// </remarks>
    public event Action<Vector2>? OnDragged;

    public IS14EditorNode()
    {
        RobustXamlLoader.Load(this);

        MouseFilter = MouseFilterMode.Stop;
    }

    public void Initialize(IS14DraftNode node, SpriteSystem sprites)
    {
        Node = node;
        Refresh(sprites);
    }

    public void Refresh(SpriteSystem sprites)
    {
        NameLabel.Text = Node.Name;
        ToolTip = $"{Node.Id}\n{Node.Name}";

        try
        {
            IconRect.Texture = sprites.Frame0(Node.Icon);
        }
        catch (Exception)
        {
            // A sprite path typed by hand may simply not exist yet; the node still has to draw.
            IconRect.Texture = null;
        }

        UpdatePanel();
    }

    public void SetSelected(bool selected)
    {
        Selected = selected;
        UpdatePanel();
    }

    public void SetBroken(bool broken)
    {
        Broken = broken;
        UpdatePanel();
    }

    protected override void KeyBindDown(GUIBoundKeyEventArgs args)
    {
        base.KeyBindDown(args);

        if (args.Function != EngineKeyFunctions.UIClick)
            return;

        args.Handle();
        OnPressed?.Invoke(this);
    }

    protected override void MouseMove(GUIMouseMoveEventArgs args)
    {
        base.MouseMove(args);

        // Also fires on a plain hover; the map ignores it unless a drag is actually running.
        OnDragged?.Invoke(args.Relative);
    }

    protected override void KeyBindUp(GUIBoundKeyEventArgs args)
    {
        base.KeyBindUp(args);

        if (args.Function != EngineKeyFunctions.UIClick)
            return;

        args.Handle();
        OnReleased?.Invoke();
    }

    private void UpdatePanel()
    {
        var border = Broken
            ? Color.FromHex("#a33b40")
            : Node.Hidden
                ? Color.FromHex("#9a6ef0")
                : Color.FromHex("#4972A1");

        PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#1d1d21"),
            BorderColor = Selected ? Color.White : border,
            BorderThickness = new Thickness(Selected ? 3 : 2),
        };
    }
}
